    def check_former_name(self):
        q = self.install or {}
        for i in q.get("legacyInstances", []):
            self.r.error("former.running", "The shell under its former name is running",
                         "Kitasan-Shell runs from %s (pid %s). With Sumi Shell started too there would be two shells: "
                         "two sets of shortcuts, two notification servers and two polkit agents." % (
                             self.pretty(i["path"]), i["pid"]),
                         "Stop it first (`systemctl --user stop kitasan-shell`, or quit the exec-once one), unlocked.")
        for c in q.get("legacyCopies", []):
            self.r.info("former.copy", "A copy of the shell under its former name is still installed",
                        "%s is Kitasan-Shell; Sumi Shell doesn't use or change it." % self.pretty(c),
                        "Keep it while you might go back; remove it by hand (or with its own `install.sh uninstall`) "
                        "once you don't.")
        old_inst = os.path.join(self.state, "kitasan-shell", "install", "manifest.json")
