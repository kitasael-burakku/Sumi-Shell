#!/usr/bin/env python3
"""Sumi Shell — `install.sh check`: what this machine has and what would get in the way. Portability F6c, 2026-10-13.

    check.py --tree <sumi/> [--json]

READ-ONLY. It runs `qs`, `hyprctl`, `systemctl --user show/is-active/show-environment/list-unit-files`, `busctl` (read
methods), `fc-list` and `qtpaths`, reads files under $HOME, $XDG_* and /proc, and imports the tree's own
scripts/capabilities.py (the same detection as Settings → System → Environment). It never starts, stops, enables or
writes anything, installs nothing and repairs nothing: it describes the state, even when it is incompatible.

Every finding has a level:
  error    Sumi Shell can't start, can't be reached, or a core function (locking, unlocking, starting) will fail
  warning  a feature will be missing or something is likely to conflict
  info     facts worth knowing (versions, which copy runs, what is unavailable and why)
and a cause, the evidence it saw and, when there is one, a fix.

Exit status: 0 = no errors (warnings allowed), 1 = at least one error, 2 = the checker itself failed (bad arguments, an
unreadable tree, an internal error). The counts are in the report, not in the exit status.

Environment overrides used only by the tests: KT_CAPS_PROC_DIR (a fake /proc, shared with capabilities.py),
KT_CHECK_QTPATHS (directories to look for qtpaths in), KT_CHECK_DBUS_DIRS (the D-Bus service directories).
"""
import argparse
import glob
import importlib
import importlib.util
import json
import os
import re
import shutil
import sys

sys.dont_write_bytecode = True

installer_spec = importlib.util.spec_from_file_location("sumi_installer", os.path.join(os.path.dirname(__file__), "installer.py"))
installer = importlib.util.module_from_spec(installer_spec)
installer_spec.loader.exec_module(installer)
qml_requirements = installer.load_module("sumi_qml_requirements", "packaging/qml_requirements.py")

FORMAT = "sumi-check"
VERSION = 1
# Versions this release was tested against. Other versions are NOT treated as incompatible: they get a warning, and what
# decides an error is a capability the shell really uses (`qs ipc call`, `--no-duplicate`, GNU `timeout`…).
QS_TESTED = (0, 3, 2)
HYPR_TESTED = (0, 56)
# Hyprland 0.57 only reads Lua configuration (".conf configs are no longer supported", PR #15539). Without hyprland.lua it
# writes a default one with this line, even when a hyprland.conf is there (measured with 0.57.0, 2026-10-30).
HYPR_LUA_ONLY = (0, 57)
HYPR_AUTOGENERATED = re.compile(r"^\s*hl\.config\(\s*\{\s*autogenerated\s*=\s*true\s*\}\s*\)", re.M)
PY_MIN = (3, 11)
UNITS = ("sumi-shell.service", "sumi-lock-rescue.service")
NOTIF = "org.freedesktop.Notifications"
POLKIT_AGENT = re.compile(r"(polkit.*agent|policykit.*agent|^lxpolkit$|^hyprpolkitagent$|^soteria$|^mate-polkit$)")
NOT_AGENT = {"polkit-agent-helper-1", "polkitd"}


class Report:
    def __init__(self):
        self.findings = []

    def add(self, level, fid, title, cause="", fix="", evidence=""):
        self.findings.append({"level": level, "id": fid, "title": title, "cause": cause, "fix": fix,
                              "evidence": evidence})

    def error(self, *a, **k):
        self.add("error", *a, **k)

    def warning(self, *a, **k):
        self.add("warning", *a, **k)

    def info(self, *a, **k):
        self.add("info", *a, **k)

    def counts(self):
        c = {"error": 0, "warning": 0, "info": 0}
        for f in self.findings:
            c[f["level"]] += 1
        return c


def load_caps(tree):
    path = os.path.join(tree, "scripts", "capabilities.py")
    spec = importlib.util.spec_from_file_location("sumi_capabilities", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def vtuple(text, n=3):
    m = re.search(r"(\d+)\.(\d+)(?:\.(\d+))?", text or "")
    if not m:
        return None
    return tuple(int(x or 0) for x in m.groups())[:n]


def vstr(t):
    return ".".join(str(x) for x in t)


class Checker:
    def __init__(self, tree, caps, args):
        self.tree = tree
        self.caps = caps
        self.r = Report()
        self.home = caps.HOME
        self.config = caps.CONFIG
        self.state = caps.STATE
        self.data = os.environ.get("XDG_DATA_HOME") or os.path.join(self.home, ".local", "share")
        self.sig = os.environ.get("HYPRLAND_INSTANCE_SIGNATURE", "")
        self.in_hypr = False
        self.install = None
        self.settings = {}
        self.args = args

    def run(self, argv, timeout=None):
        return self.caps.run(argv, timeout or self.caps.PROBE_TIMEOUT)

    def pretty(self, p):
        return self.caps.pretty_tree(p) if p else p

    # ---- the tree ----------------------------------------------------------------------------------------------

    def check_tree(self):
        if not os.path.isfile(os.path.join(self.tree, "shell.qml")):
            raise SystemExit("not a Sumi Shell tree (no shell.qml): " + self.tree)
        try:
            with open(os.path.join(self.tree, "version.json")) as f:
                v = json.load(f)
            ok = isinstance(v.get("version"), str) and isinstance(v.get("apiVersion"), int)
        except (OSError, ValueError, AttributeError):
            v, ok = {}, False
        if ok:
            self.r.info("tree.version", "Checking Sumi Shell %s (API %d) at %s" % (v["version"], v["apiVersion"],
                                                                                   self.pretty(self.tree)))
        else:
            self.r.error("tree.version", "This Sumi Shell tree has no readable version.json",
                         "The tree is incomplete or damaged; a shell started from it reports version \"unknown\".",
                         "Get the tree again (git checkout / reinstall the package).", self.pretty(self.tree))
        legacy = os.path.join(self.tree, "colors.json")
        if os.path.isfile(legacy):
            self.r.info("tree.legacy-colors", "The tree contains a generated colors.json (legacy)",
                        "Since 0.3 the generated palette lives in $XDG_STATE_HOME/sumi-shell/; this file is only a "
                        "fallback and is not part of a distribution.", evidence=self.pretty(legacy))

    # ---- toolchain ---------------------------------------------------------------------------------------------

    def check_python(self):
        v = sys.version_info[:3]
        self.r.info("python.version", "Python %s" % vstr(v), evidence=sys.executable)

    def check_quickshell(self):
        qs = installer.quickshell_path()
        if not qs:
            other = shutil.which("quickshell")
            self.r.error("quickshell.missing", "The `qs` command was not found" + (" (but `quickshell` was)" if other else ""),
                         "Sumi Shell is a Quickshell configuration; its unit, its lock helper and its scripts call `qs`.",
                         "Install Quickshell %s or newer (Arch: `pacman -S quickshell`)%s." % (
                             vstr(QS_TESTED), "; it normally installs `qs` next to `quickshell`" if other else ""),
                         other or "")
            return
        # Lo que la shell USA de verdad: `qs ipc call` (helper del Lock, notif-server, ExecReload) y `--no-duplicate`
        missing = installer.missing_qs_features(qs, self.run)
        if missing:
            self.r.error("quickshell.capabilities", "Couldn't verify " + " and ".join(missing),
                         "The shell's unit starts it with --no-duplicate and the lock helper talks to it with "
                         "`qs ipc call`; without them locking and starting fail.",
                         "Install Quickshell %s or newer." % vstr(QS_TESTED), qs)
        rc, out, err = self.run([qs, "--version"])
        v = vtuple(out)
        line = (out.strip().splitlines() or [""])[0]
        if v is None:
            self.r.warning("quickshell.version", "Couldn't read Quickshell's version",
                           "`qs --version` printed something unexpected; the capabilities above still count.",
                           evidence=(out or err).strip()[:120])
        elif v[:3] != QS_TESTED:
            self.r.warning("quickshell.version", "Quickshell %s has not been tested with this release (tested: %s)" % (
                vstr(v), vstr(QS_TESTED)),
                "Not known to be incompatible: Quickshell 0.x changes some behaviour between releases and parts of the "
                "shell compensate for what was measured on %s." % vstr(QS_TESTED),
                "Nothing to do if it works; report what doesn't.", line)
        else:
            self.r.info("quickshell.version", "Quickshell %s" % vstr(v), evidence=qs)

    def check_modules(self):
        paths, how, mods, unseen, absent = qml_requirements.inspect(self.tree, self.run)
        searched = ", ".join(paths) or "nowhere"
        # Un wrapper puede proporcionar rutas que qtpaths y el entorno no conocen.
        if unseen:
            self.r.warning("modules.unknown", "Couldn't verify the %d QML modules the shell imports" % len(mods),
                           "%s not found in the QML module directories this check knows about (%s). Quickshell may load "
                           "its modules from somewhere else (for example a wrapper that sets QML2_IMPORT_PATH), so this "
                           "is NOT a confirmed absence." % (" and ".join(unseen) or "No module directory", searched),
                           "Start the shell once (`qs -c sumi` in a terminal): a missing module makes it fail with "
                           "\"module … is not installed\". Setting QML_IMPORT_PATH lets this check look there.")
            return
        missing = [m for m in absent if m not in qml_requirements.OPTIONAL_MODULES]
        optional_missing = [m for m in absent if m in qml_requirements.OPTIONAL_MODULES]
        found = len(mods) - len(absent)
        if missing:
            ex = ", ".join("%s (%s)" % (m, sorted(mods[m])[0]) for m in missing[:6])
            self.r.error("modules.missing", "%d QML module(s) the shell imports are not installed next to the others" % len(missing),
                         "Quickshell's and Qt's base modules are in %s, but these are not: %s. One missing module makes "
                         "the whole configuration fail to load. (This check reads qmldir files; it doesn't load the "
                         "plugins.)" % (searched, ", ".join(missing)),
                         "Install a Quickshell built with all its modules and the Qt QML modules (Arch: quickshell and "
                         "qt6-declarative).", "first importer: " + ex)
        for m in optional_missing:
            self.r.warning("modules.optional", "Optional QML module %s is not installed" % m,
                           "Without it: " + qml_requirements.OPTIONAL_MODULES[m] + ".", "Install it (Arch: qt6-multimedia).",
                           ", ".join(sorted(mods[m])))
        self.r.info("modules.found", "%d of %d QML modules found" % (found, len(mods)),
                    evidence="import paths: " + searched + " (from " + ", ".join(sorted(set(how))) + ")")

    def check_gnu(self):
        probes = [("find", ["find", "/dev/null", "-maxdepth", "0", "-printf", ""], "scanning the PATH for apps"),
                  ("stat", ["stat", "-c", "%s", "/dev/null"], "update checks and file permissions"),
                  ("env", ["env", "-C", "/", "true"], "running tasks in a directory"),
                  ("timeout", ["timeout", "1", "true"], "the lock helper's bounded calls")]
        bad = []
        for name, argv, use in probes:
            rc, out, err = self.run(argv)
            if rc != 0:
                bad.append((name, use))
        if any(n == "timeout" for n, _ in bad):
            self.r.error("tools.timeout", "`timeout` doesn't work here",
                         "The lock helper bounds every call to Hyprland and to the shell with `timeout`; without it a hung "
                         "call can delay or prevent locking.", "Install GNU coreutils.")
        others = [(n, u) for n, u in bad if n != "timeout"]
        if others:
            self.r.warning("tools.gnu", "Some GNU coreutils/findutils options are missing",
                           "The shell uses GNU options that BusyBox and BSD tools lack; these failed: " +
                           ", ".join("%s (used for %s)" % nu for nu in others) + ".",
                           "Install GNU coreutils and findutils.")
        if not bad:
            self.r.info("tools.gnu", "GNU coreutils and findutils features are there (find -printf, stat -c, env -C, timeout)")

    def check_hyprland(self):
        if self.sig:
            rc, out, err = self.run(["hyprctl", "-j", "version"])
            try:
                v = vtuple(json.loads(out).get("version") or json.loads(out).get("tag"))
                self.in_hypr = True
            except (ValueError, AttributeError, TypeError):
                v = None
            if v is None:
                self.r.warning("hyprland.session", "HYPRLAND_INSTANCE_SIGNATURE is set but Hyprland doesn't answer",
                               "The signature may be stale (a Hyprland that exited) or hyprctl is missing.",
                               "Run the check from a terminal inside Hyprland.", (err or out).strip()[:120])
        else:
            v = None
            exe = shutil.which("Hyprland") or shutil.which("hyprland")
            if exe:
                rc, out, err = self.run([exe, "--version"])
                v = vtuple(out)
            self.r.info("hyprland.session", "Not inside a Hyprland session: session checks are skipped",
                        "Without HYPRLAND_INSTANCE_SIGNATURE the check can't ask the compositor, the units' environment "
                        "or who handles the lock.", "Run it again from a terminal inside Hyprland for the full picture.")
        installed = v if not self.in_hypr else None
        exe = shutil.which("Hyprland") or shutil.which("hyprland")
        if self.in_hypr and exe:
            rc, out, err = self.run([exe, "--version"])
            installed = vtuple(out)
        if v is None and not (shutil.which("Hyprland") or shutil.which("hyprland")) and not self.in_hypr:
            self.r.error("hyprland.missing", "Hyprland is not installed",
                         "Sumi Shell is a Hyprland shell; other compositors are not supported.", "Install Hyprland.")
            return
        if v is not None:
            if v[:2] < HYPR_TESTED:
                self.r.warning("hyprland.version", "Hyprland %s has not been tested (tested: %d.%d)" % ((vstr(v),) + HYPR_TESTED),
                               "Not known to be incompatible; older releases may lack options or dispatchers the shell "
                               "uses.", "Nothing to do if it works; updating Hyprland is the safe choice.")
            else:
                self.r.info("hyprland.version", "Hyprland %s%s" % (vstr(v), "" if self.in_hypr else " (installed)"))
        self.check_config_dialect(v if self.in_hypr else None, installed)
        if self.in_hypr:
            rc, out, err = self.run(["hyprctl", "-j", "getoption", "misc:allow_session_lock_restore"])
            try:
                d = json.loads(out)
                on = bool(d.get("int", d.get("bool", False)))
            except (ValueError, AttributeError):
                on = None
            if on is False:
                self.r.warning("hyprland.lock-restore", "misc:allow_session_lock_restore is off",
                               "If the shell crashes with the screen locked, it can't take the lock back; the session stays "
                               "on Hyprland's \"lock dead\" screen until hyprlock or a TTY rescues it.",
                               "Add the option (sumi/examples/hyprland/sumi.lua; sumi.conf only with Hyprland "
                               "0.56 or older).")
            elif on:
                self.r.info("hyprland.lock-restore", "misc:allow_session_lock_restore is on")

    def check_config_dialect(self, running, installed):
        """Hyprland ≥ 0.57 sólo lee Lua: avisar si la config del usuario sigue en hyprland.conf (2026-10-30)."""
        known = [x for x in (running, installed) if x]
        if not known or max(known)[:2] < HYPR_LUA_ONLY:
            return
        d = os.path.join(self.config, "hypr")
        lua, conf = os.path.join(d, "hyprland.lua"), os.path.join(d, "hyprland.conf")
        if not os.path.exists(conf):
            return
        try:
            generated = bool(HYPR_AUTOGENERATED.search(open(lua, "rb").read().decode("utf-8", "replace")))
        except OSError:
            generated = None                    # no hay hyprland.lua
        if generated is False:
            return                              # la config es Lua; el hyprland.conf que quede no se lee
        later = running is not None and running[:2] < HYPR_LUA_ONLY
        newest = max(known)
        self.r.warning("hyprland.config-lua", "Your Hyprland configuration is in hyprland.conf, which Hyprland %s doesn't "
                       "read" % vstr(newest),
                       "Hyprland 0.57 and later only read Lua configuration (hyprland.lua). %s" % (
                           "This one runs %s, so it still reads it: from your next login it won't." % vstr(running)
                           if later else "It wrote a default hyprland.lua and loads that instead." if generated
                           else "Without hyprland.lua it writes a default one and loads that instead."),
                       "Move your configuration to hyprland.lua by hand (https://wiki.hypr.land/configuring/ documents the "
                       "Lua options), restart Hyprland, then run `install.sh hyprland`. hyprland.conf needs Hyprland 0.56 "
                       "or older.", "%s%s" % (self.pretty(conf), (", %s (generated)" % self.pretty(lua)) if generated else ""))

    # ---- what Environment knows ----------------------------------------------------------------------------------

    ERROR_IF_UNAVAILABLE = {"runtime.python", "lock.pam"}
    WARN_IF_UNAVAILABLE = {"session.systemd", "session.logind", "lock.entry", "hypr.dialect", "ui.font"}

    def check_capabilities(self):
        doc = self.caps.report()
        caps = doc["caps"]
        counts = {}
        for cid, c in caps.items():
            st = c["state"]
            counts[st] = counts.get(st, 0) + 1
            if cid in ("shell.install", "session.hyprland"):
                continue
            label = "%s: %s" % (cid, c.get("reason") or c.get("provider") or st)
            if st == "unavailable" and cid in self.ERROR_IF_UNAVAILABLE:
                self.r.error("caps." + cid, "%s is unavailable" % cid, c.get("reason", ""),
                             {"runtime.python": "Install Python %s or newer." % vstr(PY_MIN),
                              "lock.pam": "Choose a PAM service that exists in Settings → Lock screen, or restore "
                                          "/etc/pam.d/login."}.get(cid, ""))
            elif st == "unavailable" and cid in self.WARN_IF_UNAVAILABLE:
                self.r.warning("caps." + cid, "%s is unavailable" % cid, c.get("reason", ""),
                               {"ui.font": "Choose an installed UI/code family in Theme → Typography and a font covering the icon map. "
                                           "No font is installed automatically."}.get(cid, ""))
            elif st in ("unavailable", "degraded", "unknown"):
                self.r.info("caps." + cid, label + (" (%s)" % st))
        self.r.info("caps.summary", "Environment: " + ", ".join("%d %s" % (n, s) for s, n in sorted(counts.items())),
                    evidence="the same detection as Settings → System → Environment (%d ms)" % doc.get("durationMs", 0))

    # ---- copies, hiding and reachability (F6a/F6b) --------------------------------------------------------------

    def check_install(self):
        q = self.caps.q_install()
        self.install = q
        c = self.caps.c_install({"install": q})
        det = c.get("detail", {})
        st = c["state"]
        if st == "unknown":
            self.r.warning("install.unknown", "Couldn't list the running shells", c.get("reason", ""),
                           "Run the check as the user who runs the shell, with its XDG_RUNTIME_DIR.")
        hidden = [x for x in q.get("copies", []) if x.get("hiddenBy")]
        present = [x for x in q.get("copies", []) if not x.get("absent")]
        for x in hidden:
            if x.get("absent"):
                self.r.warning("install.default-config", "A default Quickshell config hides user configs",
                               "%s exists, so Quickshell ignores every named config in that directory: a Sumi Shell "
                               "installed in %s would not be found." % (self.pretty(x["hiddenBy"]), self.pretty(x["path"])),
                               "Move the other shell into its own directory (~/.config/quickshell/<name>/) or remove it.")
            elif not q.get("resolved"):
                self.r.error("install.hidden", "The only Sumi Shell copy is hidden",
                             "%s hides %s: `qs -c sumi` finds nothing." % (self.pretty(x["hiddenBy"]),
                                                                            self.pretty(x["path"])),
                             "Move the default config (%s) into its own directory." % self.pretty(x["hiddenBy"]))
            else:
                self.r.warning("install.hidden", "A Sumi Shell copy is hidden",
                               "%s hides %s; %s is used instead." % (self.pretty(x["hiddenBy"]), self.pretty(x["path"]),
                                                                     self.pretty(q["resolved"])),
                               "Remove the copy you don't want, or move the default config.")
        running = det.get("running", [])
        if st == "degraded" and len(running) > 1:
            self.r.warning("install.multiple", c["reason"],
                           "Two instances of the shell draw two bars and fight over notifications and the lock.",
                           "Stop one (`systemctl --user stop sumi-shell`, or kill the exec-once one).")
        elif st == "degraded" and det.get("reachable") is False and running:
            self.r.warning("install.unreachable", "Commands from this environment don't reach the running shell",
                           c["reason"] + ". The running copy is %s; from here `qs -c sumi` resolves %s." % (
                               running[0]["path"], det.get("resolved") or "nothing"),
                           "Restart the shell after adding or removing a copy, or run commands with the shell's "
                           "XDG_CONFIG_HOME/XDG_CONFIG_DIRS.")
        if not present:
            self.r.info("install.none", "Sumi Shell is not installed in any config directory",
                        "Quickshell looks in $XDG_CONFIG_HOME/quickshell/sumi and $XDG_CONFIG_DIRS/quickshell/sumi.",
                        "This check describes the tree it was run from; installing is a separate step.")
        else:
            for x in present:
                v, api = self.caps.tree_version(x["path"])
                self.r.info("install.copy", "%s copy at %s%s%s" % (x["scope"].capitalize(), self.pretty(x["path"]),
                                                                    " (%s)" % v if v else " (no version.json: pre-0.4)",
                                                                    " → " + self.pretty(x["link"]) if x.get("link") else ""))
            if q.get("resolved"):
                same = os.path.realpath(q["resolved"]) == os.path.realpath(self.tree)
                self.r.info("install.resolved", "`qs -c sumi` starts %s%s" % (
                    self.pretty(q["resolved"]), " (this tree)" if same else " (not the tree being checked)"))
        if running:
            self.r.info("install.running", "Running: " + ", ".join("%s (pid %s)" % (r["path"], r["pid"]) for r in running))
        elif present:
            self.r.info("install.running", "No Sumi Shell is running")

    # ---- systemd units -----------------------------------------------------------------------------------------

    def unit_props(self, unit):
        rc, out, err = self.run(["systemctl", "--user", "show", unit, "-p", "LoadState", "-p", "FragmentPath",
                                 "-p", "UnitFileState", "-p", "ActiveState", "-p", "MainPID", "-p", "OnFailure"])
        if rc is None or rc != 0:
            return {"error": (err or out).strip()[:160] or "systemctl failed"}
        return dict(l.split("=", 1) for l in out.splitlines() if "=" in l)

    def exec_paths(self, fragment):
        res = []
        try:
            text = open(fragment).read()
        except OSError:
            return None, ""
        for m in re.finditer(r"^(Exec[A-Za-z]+)=(.*)$", text, re.M):
            cmd = m.group(2).strip().lstrip("-@:+!")
            if not cmd:
                continue
            exe = cmd.split()[0].replace("%h", self.home)
            res.append((m.group(1), exe))
        return res, text

    def check_units(self):
        bus = self.caps.q_bus("user")
        name = "org.freedesktop.systemd1"
        absent = "error" not in bus and name not in bus["names"] and name not in bus["activatable"]
        if absent:
            self.r.info("units.no-systemd", "No systemd: the shell's units are not used",
                        "Start the shell with `exec-once = qs -c sumi --no-duplicate`; there is no automatic rescue of "
                        "a dead lock without the units.")
            return
        if not shutil.which("systemctl"):
            self.r.warning("units.unknown", "systemctl is missing; the user manager state is not confirmed absent",
                           "The user bus query was inconclusive or still lists systemd as available.")
            return
        props = {u: self.unit_props(u) for u in UNITS}
        if any("error" in p for p in props.values()):
            err = next(p["error"] for p in props.values() if "error" in p)
            self.r.warning("units.unknown", "Couldn't ask the user service manager about the units", err,
                           "Run the check as the session's user (systemctl --user must work).")
            return
        shell, rescue = props["sumi-shell.service"], props["sumi-lock-rescue.service"]
        if shell.get("LoadState") != "loaded":
            self.r.info("units.none", "sumi-shell.service is not installed",
                        "The shell can still be started with exec-once; with the unit it restarts on failure and the "
                        "lock rescue runs if it dies while locked.")
            return
        frag = shell.get("FragmentPath", "")
        self.r.info("units.shell", "sumi-shell.service: %s, %s (%s)" % (shell.get("UnitFileState", "?"),
                                                                           shell.get("ActiveState", "?"), self.pretty(frag)))
        for u, p in props.items():
            if p.get("LoadState") != "loaded":
                continue
            fr = p.get("FragmentPath", "")
            for sysdir in ("/etc/systemd/user", "/usr/lib/systemd/user", "/usr/local/lib/systemd/user"):
                other = os.path.join(sysdir, u)
                if os.path.isfile(other) and os.path.realpath(other) != os.path.realpath(fr):
                    self.r.info("units.override", "%s from %s overrides %s" % (u, self.pretty(fr), other),
                                "systemd uses the user's copy; the system one is ignored.")
            paths, text = self.exec_paths(fr)
            if paths is None:
                self.r.warning("units.unreadable", "Couldn't read %s" % self.pretty(fr))
                continue
            for key, exe in paths:
                if not (os.path.isfile(exe) and os.access(exe, os.X_OK)):
                    self.r.error("units.exec-missing", "%s runs a program that doesn't exist" % u,
                                 "%s=%s: not found or not executable. The unit will fail%s." % (
                                     key, self.pretty(exe), " to start" if u == "sumi-shell.service" else ""),
                                 "Reinstall the unit for where the shell lives now.", self.pretty(fr))
            if "session-check" not in text:
                self.r.warning("units.outdated", "%s is an older unit (no session check)" % u,
                               "Before 0.4 the unit started in any graphical session and kept retrying outside "
                               "Hyprland.", "Replace it with sumi/systemd/%s." % u, self.pretty(fr))
        if "sumi-lock-rescue.service" in shell.get("OnFailure", "") and rescue.get("LoadState") != "loaded":
            self.r.error("units.no-rescue", "sumi-lock-rescue.service is missing",
                         "sumi-shell.service names it in OnFailure=: if the shell dies with the screen locked, nothing "
                         "starts hyprlock and the session stays on the \"lock dead\" screen.",
                         "Install sumi/systemd/sumi-lock-rescue.service next to the shell's unit.")
        if shell.get("UnitFileState") == "enabled" and self.in_hypr:
            rc, out, err = self.run(["systemctl", "--user", "show-environment"])
            env = dict(l.split("=", 1) for l in out.splitlines() if "=" in l) if rc == 0 else {}
            if rc == 0 and (env.get("HYPRLAND_INSTANCE_SIGNATURE") != self.sig
                            or env.get("WAYLAND_DISPLAY") != os.environ.get("WAYLAND_DISPLAY")):
                self.r.error("units.env", "The service manager doesn't have this Hyprland's environment",
                             "Units need the same HYPRLAND_INSTANCE_SIGNATURE and WAYLAND_DISPLAY as this session.",
                             "Hyprland exports it itself unless HYPRLAND_NO_SD_VARS is set. Otherwise run it at startup: "
                             "`exec-once = dbus-update-activation-environment --systemd WAYLAND_DISPLAY "
                             "HYPRLAND_INSTANCE_SIGNATURE` (hyprland.conf) or the same command in hl.exec_cmd (Lua), "
                             "then restart the unit.")
            rc, out, err = self.run(["systemctl", "--user", "is-active", "graphical-session.target"])
            if out.strip() != "active":
                self.r.warning("units.target", "graphical-session.target is not active",
                               "sumi-shell.service is enabled for graphical-session.target, which nothing started in "
                               "this session: the unit won't start at login.",
                               "Use a session that activates it (uwsm, or a hyprland-session.service), or start the shell "
                               "with exec-once instead.", "is-active: " + (out.strip() or err.strip()))

    # ---- notifications -----------------------------------------------------------------------------------------

    def read_settings(self):
        p = os.path.join(self.config, "sumi-shell", "settings.json")
        try:
            with open(p) as f:
                d = json.load(f)
        except (OSError, ValueError):
            return {}
        integ = ((d.get("shell") or {}).get("integrations") or {}) if isinstance(d, dict) else {}
        return {"notificationServer": integ.get("notificationServer"), "polkitAgent": integ.get("polkitAgent")}

    def activation_files(self):
        dirs = os.environ.get("KT_CHECK_DBUS_DIRS")
        if dirs is None:
            data_dirs = (os.environ.get("XDG_DATA_DIRS") or "/usr/local/share:/usr/share").split(":")
            dirs = ":".join([os.path.join(self.data, "dbus-1", "services")] +
                            [os.path.join(d, "dbus-1", "services") for d in data_dirs if d])
        res = []
        for d in dirs.split(":"):
            for f in sorted(glob.glob(os.path.join(d, "*.service"))):
                try:
                    text = open(f, errors="replace").read()
                except OSError:
                    continue
                if re.search(r"^Name=%s\s*$" % re.escape(NOTIF), text, re.M):
                    sd = re.search(r"^SystemdService=(.*)$", text, re.M)
                    ex = re.search(r"^Exec=(.*)$", text, re.M)
                    res.append({"path": f, "systemd": sd.group(1).strip() if sd else "",
                                "exec": ex.group(1).strip() if ex else ""})
        return res

    def check_notifications(self):
        setting = self.settings.get("notificationServer")
        on = setting is True
        owner = self.caps.q_notif_owner()
        acts = self.activation_files()
        shell_pids = {str(r.get("pid")) for r in (self.install or {}).get("instances", [])}
        mine = [a for a in acts if a["systemd"] == "sumi-shell.service" or "sumi" in a["exec"]]
        others = [a for a in acts if a not in mine]
        if "error" in owner:
            self.r.warning("notifications.unknown", "Couldn't ask the session bus who shows notifications", owner["error"])
            return
        bus = self.caps.q_bus("user")
        activatable = None if "error" in bus else (NOTIF in bus.get("activatable", set()))
        who = "nobody" if not owner.get("pid") else "%s (pid %s)" % (owner.get("name") or "?", owner["pid"])
        is_shell = bool(owner.get("pid")) and str(owner["pid"]) in shell_pids
        self.r.info("notifications.owner", "Notifications: shown by %s%s; the shell's server is %s" % (
            who, " = Sumi Shell" if is_shell else "", "on" if on else "off" if setting is False else "off (default)"))
        if on and owner.get("pid") and not is_shell:
            self.r.error("notifications.conflict", "Another notification server holds the name",
                         "%s owns %s, so the shell's server (enabled in its settings) can't take it." % (who, NOTIF),
                         "Stop and disable the other server, then restart the shell; or turn the shell's server off "
                         "(`sumi/scripts/notif-server off`).")
        if not on and mine and activatable is False:
            self.r.warning("notifications.stale-activation", "An activation file points at the shell, but the bus hasn't loaded it",
                           "%s activates sumi-shell.service, but the session bus doesn't list %s as activatable (it "
                           "reads the directory on reload). It will act once the bus reloads." % (
                               self.pretty(mine[0]["path"]), NOTIF),
                           "Remove the file (`sumi/scripts/notif-server off` does it) or turn the server on.")
        elif not on and mine:
            self.r.error("notifications.stale-activation", "D-Bus activation points at the shell, but its server is off",
                         "%s activates sumi-shell.service for %s: a notification sent while nobody holds the name "
                         "starts or waits for the shell, which won't take it, and the sender waits ~25 s." % (
                             self.pretty(mine[0]["path"]), NOTIF),
                         "Remove that file (`sumi/scripts/notif-server off` does it) or turn the server on "
                         "(`notif-server shell`).")
        if not owner.get("pid") and activatable is False:
            self.r.warning("notifications.none", "No notification server",
                           "Nobody holds %s and the session bus can't activate one: apps that send notifications get an "
                           "error." % NOTIF,
                           "Turn on the shell's server (`sumi/scripts/notif-server shell`) or install another one.")
        elif not owner.get("pid") and activatable is None:
            self.r.info("notifications.unverified", "Nobody shows notifications now; couldn't check whether one can be started",
                        "The session bus didn't answer ListActivatableNames: %s." % bus.get("error", "?"))
        if on and others:
            self.r.info("notifications.fallback", "Other servers can be activated if the shell is not running: " +
                        ", ".join(self.pretty(a["path"]) for a in others))

    # ---- polkit ------------------------------------------------------------------------------------------------

    def check_polkit(self):
        on = self.settings.get("polkitAgent") is True
        procs = self.caps.q_procs()
        agents = []
        for pid, comm, cmd in procs.get("list", []):
            exe = os.path.basename(cmd.split()[0]) if cmd else comm
            name = exe if POLKIT_AGENT.search(exe) else (comm if POLKIT_AGENT.search(comm) else "")
            if name and name not in NOT_AGENT:
                agents.append("%s (pid %d)" % (name, pid))
        rc, out, err = self.run(["systemctl", "--user", "list-unit-files", "--state=enabled", "--no-legend",
                                 "--type=service"]) if shutil.which("systemctl") else (None, "", "")
        units = [l.split()[0] for l in out.splitlines() if l.strip() and "polkit" in l.split()[0]] if rc == 0 else []
        self.r.info("polkit.state", "Polkit: the shell's agent is %s; other agents running: %s" % (
            "on" if on else "off", ", ".join(agents) or "none"))
        if on and agents:
            self.r.warning("polkit.conflict", "Another polkit agent seems to be running",
                           "%s looks like an authentication agent (recognised by its process name). Only one agent can "
                           "register per session: if it is one, the shell's agent (enabled) fails and password prompts come "
                           "from the other." % agents[0],
                           "Stop and disable the other agent, or turn the shell's agent off in Settings → Shell → General.")
        elif on and units:
            self.r.warning("polkit.unit", "A unit that looks like a polkit agent is enabled",
                           "%s would start another agent at login and the shell's agent would fail to register." % ", ".join(units),
                           "Disable it (`systemctl --user disable %s`) if the shell is your agent." % units[0])
        if not on and not agents:
            self.r.warning("polkit.none", "No polkit authentication agent was detected",
                           "No agent process is running and the shell's agent is off: actions that need a password "
                           "(system services, network changes) would be refused without a prompt. An agent built into "
                           "another program (for example another shell) is not visible to this check.",
                           "Turn on the shell's agent in Settings → Shell → General, or run another agent.")

