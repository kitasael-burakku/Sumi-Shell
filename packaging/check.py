        news = [os.path.join(b, "sumi-shell") for b in (self.config, self.state, self.data)
                if os.path.isdir(os.path.join(b, "sumi-shell"))]
        rec = os.path.join(self.state, "sumi-shell", "identity-migration-v1.json")
        if olds and not os.path.isfile(rec):
            if news:
                self.r.warning("former.state", "State of both names exists and wasn't migrated by the installer",
                               "%s and %s: the shell only reads the second." % (
                                   ", ".join(self.pretty(p) for p in olds), ", ".join(self.pretty(p) for p in news)),
                               "Compare them by hand; `install.sh migrate identity-v1` refuses while both exist.")
            else:
                self.r.warning("former.state", "Settings and data of the former name haven't been copied",
                               "%s exist; Sumi Shell reads …/sumi-shell and would start with defaults (calendar, "
                               "settings, theme)." % ", ".join(self.pretty(p) for p in olds),
                               "`install.sh migrate identity-v1` shows the copy; run it with --apply with every shell "
                               "stopped (the originals stay).")
        elif olds:
            self.r.info("former.state", "The former name's state was copied (the originals are kept on purpose)",
                        evidence=self.pretty(rec))
        mcfg = os.path.join(self.config, "matugen", "config.toml")
        try:
            with open(mcfg, encoding="utf-8", errors="replace") as f:
                text = f.read()
        except OSError:
            text = ""
        if "kitasan-shell/colors.json" in text:
            self.r.warning("former.matugen", "Your matugen config still writes the shell's colours to the former name",
                           "%s has an output_path ending in kitasan-shell/colors.json; Sumi Shell reads "
                           "…/sumi-shell/colors.json, so dynamic colours won't reach it." % self.pretty(mcfg),
                           "Change that output_path (and the template's input_path, if it names quickshell/kitasan) to "
                           "the sumi-shell / quickshell/sumi paths.")

