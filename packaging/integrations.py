def waits_for_lock(general):
    """¿Retiene hypridle la suspensión hasta que la sesión está bloqueada? (medido en MP-7, hypridle 0.1.8)
    3 → sí; 2 o sin poner → sí sólo si lock_cmd contiene «hyprlock» y before_sleep_cmd es `loginctl lock-session`;
    0 / 1 → no (1 suelta la suspensión al LANZAR before_sleep_cmd, sin esperar a que acabe)."""
    v = (general.get("inhibit_sleep") or "").strip()
    if v == "3":
        return True
    if v in ("", "2"):
        return "hyprlock" in (general.get("lock_cmd") or "") and bool(REQUESTER.match(general.get("before_sleep_cmd") or ""))
    return False


def hypridle_target(roots, tree):
    lc = I.load_module("sumi_lockchain", os.path.join("packaging", "lockchain.py"))
    t = {"manual": [], "notes": []}
    pids = lc.processes("hypridle")
    if pids is None:
        t["manual"].append("the process list can't be read")
        return t
    mains = []
    for pid in pids:
        main, how = lc.locate_hypridle(pid)
        start = lc.proc_start(pid)
        mains.append((pid, main, how, start, lc.proc_origin(pid)))
    if len({m[1] for m in mains}) > 1:
        t["manual"].append("more than one hypridle runs, with different configurations")
        return t
    if mains:
        pid, main, how, start, origin = mains[0]
        t.update(running=True, pids=[m[0] for m in mains], main=main, start=min(m[3] or 0 for m in mains), origin=origin,
                 count=len(mains))
        if main is None:
            t["manual"].append(how)
            return t
    else:
        cfgs, unknown = lc.next_start_configs([os.path.join(roots.real["config"], "hypr")])
        existing = [c for c, src in cfgs if os.path.exists(c)]
        if unknown or len(existing) != 1:
            t["manual"].append("hypridle isn't running and its configuration can't be pinned down (%s)" % (
                ", ".join(unknown) or "%d candidates" % len(existing)))
            return t
        t.update(running=False, main=existing[0], origin="", count=0)
        t["notes"].append("hypridle isn't running: the change takes effect when it starts")
    if not os.path.exists(t["main"]):
        t["manual"].append("%s doesn't exist: the installer doesn't create a hypridle configuration (add the lines by "
                           "hand)" % t["main"])
        return t
    conf = lc.read_hypridle(t["main"])
    if conf["error"]:
        t["manual"].append(conf["error"])
    if t.get("running"):
        newer = lc.changed_since(conf["files"], t["start"])
        if newer:
            t["manual"].append("hypridle started before its configuration last changed (%s): what it runs now can't be "
                               "known. Restart it first (%s)" % (", ".join(newer), lc.restart_hint(t["origin"])))
    t["general"] = conf["general"]
    t["files"] = conf["files"]
    t["manual"] += file_policy(t["main"], roots)
    return t


