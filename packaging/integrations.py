def render_hyprland(dialect, mid, colors=None, skip=()):
    """`colors`: la ruta ABSOLUTA del archivo del borde (junto al fragmento; F-e): no se depende del entorno de Hyprland.
    `skip` (2026-11-11, sólo Lua): atajos cuya combinación ya usaba el usuario; no se ligan y el fragmento dice cómo
    ligarlos a otra tecla (antes un solo choque rechazaba el fragmento entero: con la config de serie, SUPER+C/SUPER+R)."""
    binds = bind_table()
    if dialect == "lua":
        lines = ["-- Sumi Shell for Hyprland (Lua). Written by `install.sh hyprland --apply` (install %s)." % mid,
                 "-- Remove it with `install.sh hyprland --revert`. If you edit it, the installer keeps your changes and",
                 "-- stops managing it.",
                 "hl.config({ misc = { allow_session_lock_restore = true, session_lock_xray = true } })"]
        lines += LUA_LAYER_RULES
        # F-e (2026-11-04): el borde de las ventanas con los colores de la shell, sólo si `install.sh theme-apps --apply
        # hyprland` lo pidió (el proveedor de tema escribe ese archivo; sin él, nada cambia)
        if colors:
            lines.append('do local ok, c = pcall(dofile, %s); if ok and type(c) == "table" then hl.config({ general = '
                         '{ col = c } }) end end' % lua_string(colors))
        left = [b for b in binds if b["name"] in skip]
        if left:
            lines.append("-- Left out: their keys were already bound in your configuration. To use them, bind another key")
            lines.append("-- (keep the description: Sumi Shell's shortcuts help reads it):")
        for b in left:
            lines.append('--   hl.bind("<keys>", hl.dsp.global("sumi:%s"), { description = "%s" })  -- default: %s' % (
                b["name"], describe_bind(b), " + ".join([m.upper() for m in b["mods"]] + [b["key"].upper()])))
        for b in binds:
            if b["name"] in skip:
                continue
            keys = " + ".join([m.upper() for m in b["mods"]] + [b["key"].upper()])
            lines.append('hl.bind("%s", hl.dsp.global("sumi:%s"), { description = "%s" })' % (keys, b["name"],
                                                                                              describe_bind(b)))
    else:
        # CONGELADO (2026-10-30): hyprland.conf sólo para Hyprland ≤ 0.56; no se le añade nada nuevo
        lines = ["# Sumi Shell for Hyprland (hyprland.conf). Written by `install.sh hyprland --apply` (install %s)." % mid,
                 "# Remove it with `install.sh hyprland --revert`. If you edit it, the installer keeps your changes and",
                 "# stops managing it.",
                 "misc {", "    allow_session_lock_restore = true", "    session_lock_xray = true", "}",
                 "layerrule = match:namespace sumi-shell, blur on, ignore_alpha 0.4"]
        for b in binds:
            lines.append("bindd = %s, %s, %s, global, sumi:%s" % (" ".join(b["mods"]), b["key"], describe_bind(b),
                                                                     b["name"]))
    return ("\n".join(lines) + "\n").encode()


def lua_string(s):
    """Un literal de cadena Lua seguro para una ruta (escapes de \\ y comillas; sin saltos de línea)."""
    if "\n" in s or "\r" in s or "\0" in s:
        raise I.Refused(["the path %r can't be written into a Lua file" % s])
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


