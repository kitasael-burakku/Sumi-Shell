def hyprland_target(roots):
    """{instance, pid, start, main, dialect, autoreload, manual: [...], notes: [...]} sin escribir nada."""
    t = {"manual": [], "notes": []}
    sig = os.environ.get("HYPRLAND_INSTANCE_SIGNATURE", "")
    inst = [i for i in (hj("instances") or []) if i.get("instance") == sig]
    if not sig or not inst:
        t["manual"].append("no running Hyprland answers here (HYPRLAND_INSTANCE_SIGNATURE); run this from inside your "
                           "Hyprland session")
        t["running"] = False
    else:
        t.update(running=True, pid=inst[0].get("pid"), start=inst[0].get("time"))
    lc = I.load_module("sumi_lockchain", os.path.join("packaging", "lockchain.py"))
    log = os.path.join(os.environ.get("XDG_RUNTIME_DIR", ""), "hypr", sig, "hyprland.log")
    used = None
    for line in (lc._read(log) or "").splitlines():
        # 0.56: «Using lua config found at» / «using legacy config at»; 0.57: «[cfg] Regular config at» (medido)
        m = re.search(r"(?:Using lua config found at|using legacy config at|Using config:|Regular config at) (.+?)\s*$", line)
        if m:
            used = m.group(1)
            break
    env = lc.proc_env(t.get("pid")) if t.get("pid") else {}
    args = (lc._read(os.path.join(lc.PROC, str(t.get("pid")), "cmdline"), "rb") or b"").decode("utf-8", "replace").split("\0")
    if env.get("HYPRLAND_CONFIG"):
        t["manual"].append("Hyprland was started with HYPRLAND_CONFIG=%s (not measured): add the integration by hand"
                           % env["HYPRLAND_CONFIG"])
    cfg = (env.get("XDG_CONFIG_HOME") or os.path.join(env.get("HOME") or roots.paths["home"], ".config")) if env else \
        roots.real["config"]
    explicit = None
    for i, a in enumerate(args):
        if a in ("-c", "--config") and i + 1 < len(args):
            explicit = args[i + 1]
        elif a.startswith("--config="):
            explicit = a.split("=", 1)[1]
    if explicit is not None:
        # con -c, el log de la config Lua no dice la ruta (medido): manda el argumento del propio proceso, desde SU cwd
        p = os.path.expanduser(explicit)
        if not os.path.isabs(p):
            try:
                p = os.path.join(os.readlink(os.path.join(lc.PROC, str(t.get("pid")), "cwd")), p)
            except OSError:
                p = None
        computed = os.path.normpath(p) if p else None
        t["notes"].append("Hyprland was started with -c %s" % explicit)
        if computed is None:
            t["manual"].append("Hyprland was started with a relative -c and its working directory can't be read")
    else:
        lua, conf = os.path.join(cfg, "hypr", "hyprland.lua"), os.path.join(cfg, "hypr", "hyprland.conf")
        computed = lua if os.path.exists(lua) else (conf if os.path.exists(conf) else None)
    if used and computed and os.path.realpath(used) != os.path.realpath(computed):
        t["manual"].append("Hyprland says it loaded %s but this environment points at %s" % (used, computed))
    t["main"] = used or computed
    if not t["main"]:
        t["manual"].append("can't tell which configuration file Hyprland loaded")
        return t
    if not used:
        t["notes"].append("not confirmed by a running Hyprland")
    t["dialect"] = "lua" if t["main"].endswith(".lua") else "conf"
    if t.get("running"):
        rc, out, err = hyprctl("eval", "local _ = 0")
        probe = "lua" if out.strip() == "ok" else ("conf" if "only supported with the lua config manager" in out + err
                                                    else None)
        if probe != t["dialect"]:
            t["manual"].append("the running Hyprland's dialect (%s) doesn't match %s" % (probe or "unknown", t["main"]))
        opt = hj("getoption", "misc:disable_autoreload") or {}
        t["autoreload"] = not bool(opt.get("bool", opt.get("int", 0)))
    lua_only_check(t)
    t["manual"] += file_policy(t["main"], roots)
    return t


def lua_only_check(t):
    """Hyprland ≥ 0.57 sólo lee Lua. Una config en hyprland.conf (o el hyprland.lua que Hyprland genera cuando no
    encuentra uno, con el hyprland.conf del usuario al lado) no se integra: `migrate` y el motivo en `manual`."""
    vs = hyprland_versions(t.get("running"))
    t["versions"] = {k: vstr(v) for k, v in vs.items() if v}
    known = [v for v in vs.values() if v]
    newest = max(known) if known else None
    t["luaOnly"] = (newest[:2] >= LUA_ONLY) if newest else None
    vals = t["versions"]
    seen = ("" if not vals else next(iter(vals.values())) if len(set(vals.values())) == 1 else
            "(running %s, installed %s)" % (vals["running"], vals["installed"]))
    if t["dialect"] == "conf":
        if newest is None:
            t["manual"].append("can't tell which Hyprland version this is (neither `hyprctl -j version` nor `Hyprland "
                               "--version-json` answered): hyprland.conf is only read up to Hyprland 0.56")
        elif t["luaOnly"]:
            t["migrate"] = True
            t["manual"].append("Hyprland %s reads only Lua configuration (hyprland.lua): %s is not loaded%s"
                               % (seen, t["main"], " at your next login" if vs["running"] and vs["running"][:2] < LUA_ONLY
                                  else ""))
        return
    conf = os.path.join(os.path.dirname(t["main"]), "hyprland.conf")
    try:
        generated = bool(AUTOGENERATED.search(open(t["main"], "rb").read().decode("utf-8", "replace")))
    except OSError:
        generated = False
    if generated and os.path.exists(conf):
        t["migrate"] = True
        t["manual"].append("%s is the default configuration Hyprland writes when it finds no Lua one; your own "
                           "configuration is still in %s, which Hyprland%s doesn't read" % (
                               t["main"], conf, (" " + seen) if seen else ""))


def lua_check(path_text):
    """luac -p del candidato, sólo con un luac de la MISMA versión que la liblua de Hyprland (M3). (ok, motivo)"""
    hypr = shutil.which("Hyprland")
    luac = shutil.which("luac")
    if not hypr or not luac:
        return False, "Hyprland or luac isn't installed: a Lua configuration can't be checked without running it"
    want = hyprland_lua_version(hypr)
    rc2, out2, err2 = run_cmd([luac, "-v"])
    m2 = re.search(r"Lua (\d+\.\d+)", out2 + err2)
    if not want or not m2 or want != m2.group(1):
        return False, "luac (%s) isn't the Lua Hyprland uses (%s)" % (m2.group(1) if m2 else "?", want or "unknown")
    with tempfile.NamedTemporaryFile("wb", suffix=".lua", delete=False) as f:
        f.write(path_text)
        tmp = f.name
    try:
        rc, out, err = run_cmd([luac, "-p", tmp])
        return rc == 0, (out + err).strip().replace(tmp, "<candidate>")
    finally:
        os.unlink(tmp)


def hyprland_lua_version(hypr):
    """La Lua que Hyprland enlaza DIRECTAMENTE (readelf NEEDED; ldd también lista las de sus dependencias)."""
    readelf = shutil.which("readelf")
    if not readelf:
        return None
    rc, out, err = run_cmd([readelf, "-d", hypr])
    for m in re.finditer(r"NEEDED\)\s+Shared library: \[([^\]]+)\]", out):
        lib = m.group(1)
        mm = re.match(r"liblua-?(\d\.\d)?\.so(?:\.(\d+\.\d+))?", lib)
        if mm and (mm.group(1) or mm.group(2)):
            return mm.group(1) or mm.group(2)
    return None


def conf_check(text):
    """El final de un hyprland.conf/hypridle.conf: sin llaves abiertas ni `# hyprlang if` sin cerrar (M1: no se ejecuta)."""
    depth, cond = 0, 0
    for raw in text.decode("utf-8", "replace").split("\n"):
        s = raw.strip()
        if re.match(r"^#\s*hyprlang\s+if\b", s):
            cond += 1
        elif re.match(r"^#\s*hyprlang\s+endif\b", s):
            cond -= 1
        line = raw.split("#", 1)[0]
        depth += line.count("{") - line.count("}")
    if depth != 0:
        return False, "the file has unbalanced braces"
    if cond != 0:
        return False, "the file has an open `# hyprlang if`"
    return True, ""


def verify_fragment(data, dialect):
    """`Hyprland --verify-config` SÓLO del fragmento propio, en una carpeta temporal (M1: ejecuta lo que verifica)."""
    hypr = shutil.which("Hyprland")
    if not hypr:
        return False, "Hyprland isn't installed here"
    d = tempfile.mkdtemp(prefix="sumi-verify-")
    try:
        p = os.path.join(d, FRAG_LUA if dialect == "lua" else FRAG_CONF)
        open(p, "wb").write(data)
        env = {"PATH": "/usr/bin:/bin", "HOME": d, "XDG_CONFIG_HOME": d, "XDG_RUNTIME_DIR": d}
        rc, out, err = run_cmd([hypr, "--verify-config", "--config", p], timeout=60, env=env, cwd=d)
        ok = rc == 0 and "config ok" in out
        return ok, "" if ok else (out + err).strip()[-300:]
    finally:
        shutil.rmtree(d, ignore_errors=True)


def already_ours_or_user(main, dialect, mid):
    """(nuestros bloques, otros bloques, ¿integrado a mano?) del principal y su carpeta."""
    text = open(main, "rb").read().decode("utf-8", "replace")
    ours = text.count(">>> sumi-shell (install %s)" % mid)
    others = len(re.findall(r">>> sumi-shell \(install (?!%s)" % re.escape(mid), text))
    manual = False
    d = os.path.dirname(main)
    for folder, dirs, files in os.walk(d):
        if folder[len(d):].count("/") >= 3:
            dirs[:] = []
        for n in files:
            if n in (FRAG_LUA, FRAG_CONF) or not n.endswith((".lua", ".conf")) or n.startswith("."):
                continue
            body = open(os.path.join(folder, n), "rb").read().decode("utf-8", "replace")
            if "sumi:" in body.replace(block_text("hyprland", dialect, mid, ""), ""):
                manual = True
    return ours, others, manual


def bind_key(b):
    return (b.get("modmask"), str(b.get("key", "")).lower())


def check_binds(binds, dialect, want_present, skip=()):
    """Combinación + acción efectiva (A18: la descripción, como dato adicional en Lua, donde la acción no se ve).
    `skip`: los que el fragmento dejó fuera (su tecla era del usuario): ni se exigen ni, al revertir, se buscan."""
    table = bind_table()
    probs, seen = [], 0
    for b in table:
        if b["name"] in skip:
            continue
        k = (b["mask"], b["key"].lower())
        hits = [x for x in binds if bind_key(x) == k]
        ours = [x for x in hits if (x.get("dispatcher") == "global" and x.get("arg") == "sumi:" + b["name"]) or
                (lua_global(x) and x.get("description") == describe_bind(b))]
        if want_present:
            if len(ours) != 1:
                probs.append("%s: %d bindings of ours (want 1)" % (describe_bind(b), len(ours)))
            elif len(hits) != 1:
                probs.append("%s: its key combination also does something else" % describe_bind(b))
            elif dialect == "conf" and ours[0].get("description") != describe_bind(b):
                probs.append("%s: bound, but without its description" % describe_bind(b))
            else:
                seen += 1
        elif ours:
            probs.append("%s is still bound" % describe_bind(b))
    return seen, probs


def taken(binds):
    """{nombre: motivo} de los atajos cuya combinación ya usa otra cosa (en orden del catálogo)."""
    out = {}
    for b in bind_table():
        k = (b["mask"], b["key"].lower())
        for x in binds:
            if bind_key(x) == k and not ((x.get("dispatcher") == "global" and x.get("arg") == "sumi:" + b["name"]) or
                                         x.get("description") == describe_bind(b)):
                out.setdefault(b["name"], "%s: %s %s is already bound (%s %s)" % (
                    b["name"], "+".join(b["mods"]), b["key"], x.get("dispatcher"), x.get("arg")))
    return out


def conflicts(binds, mid_desc_ok=True):
    out = []
    table = bind_table()
    for b in table:
        k = (b["mask"], b["key"].lower())
        for x in binds:
            if bind_key(x) == k and not ((x.get("dispatcher") == "global" and x.get("arg") == "sumi:" + b["name"]) or
                                         x.get("description") == describe_bind(b)):
                out.append("%s %s is already bound (%s %s)" % ("+".join(b["mods"]), b["key"], x.get("dispatcher"),
                                                               x.get("arg")))
    return out


