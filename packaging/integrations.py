def shortcut_count():
    """Los que se LIGAN: los del contrato menos los alias sin tecla (etapa C del Dashboard, 2026-11-10: `media`)."""
    return len(bind_table())


SHORTCUT_CATALOG = os.path.join("sumi", "lib", "shortcuts.json")


def bind_table():
    """Las teclas POR DEFECTO de los atajos: el catálogo de la shell (`sumi/lib/shortcuts.json`, ayuda de atajos,
    2026-10-30), la misma fuente que la ventana de ayuda y los ejemplos (tests/api/api-check.py lo comprueba). Hasta
    entonces se leían del `.conf` de ejemplo, congelado para Hyprland ≤ 0.56. Las grafías de las teclas son las de antes
    (`space`, `Escape`…): el fragmento lleva las mismas líneas que antes (y la del 29.º, `keybinds`), en el orden del catálogo (por categoría). Sólo
    se genera en un `--apply` nuevo; los ya escritos se comprueban por combinación y descripción, no por su texto."""
    try:
        cat = json.load(open(os.path.join(I.ROOT, SHORTCUT_CATALOG)))
        out = []
        aliases = []
        for s in cat["shortcuts"]:
            # etapa C del Dashboard (2026-11-10): un alias (`media` → `mixer`) no tiene tecla por defecto ni se liga
            if s.get("alias") and not s["defaultKeys"].strip():
                aliases.append(s["name"])
                continue
            parts = [p.strip() for p in s["defaultKeys"].split("+")]
            mods, key = parts[:-1], parts[-1]
            out.append({"mods": mods, "key": key, "name": s["name"], "mask": sum(MODMASK[x.upper()] for x in mods)})
    except (OSError, ValueError, KeyError, TypeError, IndexError):
        raise I.Refused(["the shortcut catalog (%s) is missing or unreadable: the distribution is inconsistent"
                         % SHORTCUT_CATALOG])
    names = json.load(open(os.path.join(I.ROOT, "api", "contract-v1.json")))["shortcuts"]["names"]
    # los alias siguen en el contrato (registrados) aunque no se liguen
    if sorted([b["name"] for b in out] + aliases) != sorted(names) or len(out) + len(aliases) != len(names):
        raise I.Refused(["the shortcut table (%s) doesn't match the public contract: the distribution is inconsistent"
                         % SHORTCUT_CATALOG])
    return out


