class Integrations:
    def __init__(self, inst):
        self.inst = inst
        self.roots = inst.roots
        self.man = inst.man
        self.args = inst.args

    def say(self, m):
        self.inst.say(m)

    def need_install(self):
        doc = self.man.load()
        if doc is None or doc.get("status") != "installed":
            raise I.Refused(["Sumi Shell isn't installed by this installer here (or the install isn't complete): "
                             "integrations need the installed helper. See the manual steps with `install.sh %s`"
                             % self.args.cmd])
        if doc.get("transaction"):
            raise I.pending_refusal(doc["transaction"])
        return doc

    def frag_path(self, main, dialect, kind):
        return os.path.join(os.path.dirname(main), FRAG_IDLE if kind == "hypridle" else (FRAG_LUA if dialect == "lua"
                                                                                           else FRAG_CONF))

    # -- Hyprland --
    def hyprland(self):
        doc = self.man.load()
        mid = (doc or {}).get("id", "<install id>")
        t = hyprland_target(self.roots)
        rec = ((doc or {}).get("integrations") or {}).get("hyprland")
        if self.args.revert:
            return self.hyprland_revert(doc, t, rec)
        if not self.args.apply:
            return self.hyprland_preview(doc, t, rec, mid)
        return self.hyprland_apply(doc, t, rec)

    def hyprland_manual(self, t, dialect=None):
        if t.get("migrate"):
            return self.hyprland_migrate(t)
        d = dialect or t.get("dialect") or "lua"
        if t.get("luaOnly"):
            d = "lua"
        frag = self.frag_path(t.get("main") or os.path.join(self.roots.real["config"], "hypr", "hyprland.lua"), d,
                              "hyprland")
        self.say("Manual steps (nothing was changed):")
        self.say("  1. Copy %s to %s" % (os.path.join(I.ROOT, "sumi", "examples", "hyprland",
                                                      "sumi.lua" if d == "lua" else "sumi.conf"),
                                         frag.replace(FRAG_LUA, "sumi.lua").replace(FRAG_CONF, "sumi.conf")))
        self.say("     (in the directory of the configuration file Hyprland loads; with Stow, in your dotfiles' copy).")
        self.say("  2. Add one line at the END of %s: %s" % (t.get("main") or "your hyprland.lua / hyprland.conf",
                                                            'require("sumi")' if d == "lua" else
                                                            "source = <that directory>/sumi.conf"))
        self.say("  3. Check it without running it: Lua → `luac -p <file>`; then `hyprctl reload`.")
        self.say("  4. Check the bindings: `hyprctl binds` must show your keys with `global sumi:<name>` (hyprland.conf) "
                 "or %d bindings at those keys (Lua)." % shortcut_count())

    def hyprland_migrate(self, t):
        main = t.get("main") or ""
        lua = os.path.join(os.path.dirname(main) or os.path.join(self.roots.real["config"], "hypr"), "hyprland.lua")
        self.say("Nothing was changed. Hyprland 0.57 and later only read Lua configuration (hyprland.lua); hyprland.conf "
                 "is ignored, and when there is no hyprland.lua Hyprland writes a default one.")
        self.say("  1. Move your configuration to Lua by hand, in %s (Hyprland's wiki, https://wiki.hypr.land/configuring/, "
                 "documents the Lua options). Sumi Shell doesn't convert it." % lua)
        self.say("  2. Restart Hyprland (log out and back in) so it loads it, then run `install.sh hyprland` again: it adds "
                 "the Lua fragment (the same as sumi/examples/hyprland/sumi.lua).")
        self.say("  To keep hyprland.conf you need Hyprland 0.56 or older (sumi/examples/hyprland/sumi.conf is kept "
                 "for it).")

    def hyprland_preview(self, doc, t, rec, mid):
        self.say("Hyprland: %s (%s)%s" % (t.get("main") or "?", t.get("dialect") or "?",
                                          "" if t.get("running") else " · not confirmed by a running Hyprland"))
        if t.get("versions"):
            self.say("  version: " + ", ".join("%s %s" % kv for kv in sorted(t["versions"].items())))
        if rec:
            self.say("Integration: %s" % self.state_line("hyprland", rec))
        for n in t["notes"]:
            self.say("  note: " + n)
        if t["manual"]:
            self.say("Can't be done automatically:")
            for m in t["manual"]:
                self.say("  - " + m)
            self.hyprland_manual(t)
            return I.EXIT_REFUSED
        d = t["dialect"]
        frag = self.frag_path(t["main"], d, "hyprland")
        ours, others, manual = already_ours_or_user(t["main"], d, mid)
        if manual:
            self.say("Your configuration already binds Sumi Shell (`sumi:` in your files): already set up by you, "
                     "nothing to do.")
            return I.EXIT_OK
        old = open(t["main"], "rb").read()
        cand = old + (b"\n" if old and not old.endswith(b"\n") else b"") + block_text("hyprland", d, mid, frag).encode()
        ok, why = lua_check(cand) if d == "lua" else conf_check(cand)
        if not ok:
            self.say("Can't be done automatically: with the new line, %s doesn't pass the syntax check (%s)." % (
                t["main"], why))
            self.hyprland_manual(t)
            return I.EXIT_REFUSED
        binds = hj("binds") or []
        conf = conflicts(binds)
        busy = taken(binds) if d == "lua" else {}
        if busy and len(busy) == shortcut_count():
            conf = conf or ["every shortcut's key is taken"]
        elif busy:
            conf = []
        self.say("Would create %s (the %d shortcuts with descriptions, the lock options allow_session_lock_restore and "
                 "session_lock_xray, and the blur layer %s) and add at the end of %s:" % (
                     frag, shortcut_count() - len(busy), "rules plus no compositor animation on the shell's layers"
                     if d == "lua" else "rule", t["main"]))
        for line in block_text("hyprland", d, mid, frag).splitlines():
            self.say("    " + line)
        if busy and not conf:
            self.say("Left out, because your configuration already uses their keys (the fragment says how to bind "
                     "them to other keys):")
            for name in busy:
                self.say("  - " + busy[name])
        if conf:
            self.say("Refused while these key combinations are taken (Hyprland would keep both bindings):")
            for c in conf:
                self.say("  - " + c)
        self.say("Applying %s: Hyprland reloads its whole configuration%s. That runs your configuration again (Lua code, "
                 "`exec` lines). Pass --reload with --apply to allow it." % (
                     "requires a reload" if t.get("autoreload", True) else "works without a reload (automatic reload is "
                     "off), but nothing is loaded until Hyprland reloads",
                     "" if t.get("autoreload", True) else " when you allow it"))
        return I.EXIT_OK if not conf else I.EXIT_REFUSED

    def hyprland_apply(self, doc, t, rec):
        doc = self.need_install()
        mid = doc["id"]
        if t["manual"]:
            raise I.Refused(t["manual"] + ["(run `install.sh hyprland` for the manual steps)"])
        if not t.get("running"):
            raise I.Refused(["no running Hyprland to load and check the integration (A3)"])
        if rec and rec.get("status") not in ("reverted",):
            if rec.get("status") in ("loaded", "written"):
                self.say("Already applied: " + self.state_line("hyprland", rec))
                return I.EXIT_OK
            raise I.Refused(["the Hyprland integration is %s: resolve it first (`install.sh status`)" % rec.get("status")])
        if t.get("autoreload", True) and not self.args.reload:
            raise I.Refused(["with automatic reload on, writing %s makes Hyprland reload its whole configuration "
                             "(your Lua code and exec lines run again). Pass --reload to allow it" % t["main"]])
        d = t["dialect"]
        frag = self.frag_path(t["main"], d, "hyprland")
        ours, others, manual = already_ours_or_user(t["main"], d, mid)
        if manual:
            self.say("Already set up by you (`sumi:` in your configuration): nothing to do.")
            return I.EXIT_OK
        if ours or others:
            raise I.Refused(["%s already has sumi-shell blocks (%d of this install, %d of another): fix it by hand"
                             % (t["main"], ours, others)])
        if os.path.lexists(frag):
            raise I.Refused(["%s already exists and isn't this installer's" % frag])
        binds = hj("binds") or []
        busy = taken(binds) if d == "lua" else {}
        c = conflicts(binds)
        if c and (d != "lua" or len(busy) == shortcut_count()):
            raise I.Refused(["key combinations already taken: " + "; ".join(c)])
        fdata = render_hyprland(d, mid, colors_path(frag) if d == "lua" else None, list(busy))
        ok, why = verify_fragment(fdata, d)
        if not ok:
            raise I.Refused(["this Hyprland doesn't accept the fragment (`Hyprland --verify-config` of the fragment "
                             "only): " + why])
        st = os.lstat(t["main"])
        old = open(t["main"], "rb").read()
        added_nl = bool(old) and not old.endswith(b"\n")
        block = block_text("hyprland", d, mid, frag).encode()
        new = old + (b"\n" if added_nl else b"") + block
        ok, why = lua_check(new) if d == "lua" else conf_check(new)
        if not ok:
            raise I.Refused(["the configuration with the new line doesn't pass the syntax check (%s): add it by hand" % why])
        errors_before = hyprctl("configerrors")[1].strip()
        rec = {"kind": "hyprland", "status": "applying", "dialect": d, "main": t["main"], "mainIno": st.st_ino,
               "shaBefore": sha(old), "shaAfter": sha(new), "addedNewline": added_nl, "block": block.decode(),
               "fragment": frag, "fragmentSha": sha(fdata), "kept": [], "conflict": None, "loaded": False,
               "history": [], "skipped": list(busy)}
        return self.run_tx(doc, "hyprland-apply", rec, lambda tx: self.apply_steps(doc, tx, rec, fdata, new, errors_before))

    def apply_steps(self, doc, tx, rec, fdata, new, errors_before):
        kind = rec["kind"]
        rec["pendingFrom"], rec["pendingNew"] = rec["shaBefore"], rec["shaAfter"]
        self.step(doc, "fragment", lambda: create_fragment(rec["fragment"], self.roots, fdata, doc["createdDirs"]))
        res = {}

        def main():
            r, info = replace_file(rec["main"], self.roots, rec["mainIno"], rec["shaBefore"], new, doc["transaction"]["id"],
                                   os.path.basename(rec["main"]) + ".before", doc["createdDirs"])
            res["r"], res["info"] = r, info
            if r == "done":
                rec["kept"].append({"rel": info, "sha": rec["shaBefore"], "why": "%s before the integration" % rec["main"]})
                rec["status"] = "written"
            elif r == "conflict":
                rec["status"] = "conflict"
                rec["conflict"] = info
            else:
                rec["status"] = "unchanged"
        self.step(doc, "main", main)
        if res["r"] == "conflict":
            self.say_conflict(rec)                      # el principal puede llevar nuestra línea: el fragmento se queda
            return I.EXIT_REFUSED
        if res["r"] != "done":
            remove_fragment(rec["fragment"], self.roots, rec["fragmentSha"])
            raise I.Refused(["%s changed while it was being written: nothing was changed, run it again" % rec["main"]])
        if kind == "hyprland":
            return self.reload_and_verify(doc, rec, True, errors_before)
        return self.hypridle_after_write(doc, rec, True)

    def reload_and_verify(self, doc, rec, present, errors_before):
        if not self.args.reload:
            rec["loaded"] = False
            rec["status"] = "written" if present else "reverted-on-disk"
            self.say("%s, NOT confirmed as loaded: Hyprland hasn't reloaded (automatic reload is off). Run `hyprctl reload` "
                     "when you choose (it runs your configuration again), then `install.sh hyprland --verify`." % (
                         "Written" if present else "Reverted on disk"))
            return I.EXIT_OK
        res = {}

        def reload():
            rc, out, err = hyprctl("reload")
            res.update(rc=rc, out=(out + err).strip()[:200])
        self.step(doc, "reload", reload)
        rec["reload"] = {"at": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "rc": res["rc"], "reply": res["out"]}
        if res["rc"] != 0 or res["out"] != "ok":
            # Hyprland no confirmó la recarga: lo escrito se queda (es la evidencia para terminar), nada se declara cargado
            rec["loaded"] = False
            rec["status"] = "written" if present else "reverted-on-disk"
            self.say("Hyprland didn't confirm the reload (%s): the files are %s but NOT confirmed as loaded. Check Hyprland, "
                     "run `hyprctl reload`, then `install.sh hyprland --verify`." % (
                         res["out"] or "rc %s" % res["rc"], "written" if present else "reverted"))
            return I.EXIT_REFUSED
        seen, probs = 0, ["not checked"]
        for _ in range(15):
            time.sleep(0.2)
            seen, probs = check_binds(hj("binds") or [], rec["dialect"], present, rec.get("skipped") or ())
            if not probs:
                break
        new_errors = hyprctl("configerrors")[1].strip()
        if new_errors and new_errors != errors_before:
            probs.append("Hyprland reports configuration errors: " + new_errors[:200])
        rec["verified"] = {"at": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "entries": seen, "problems": probs}
        rec["loaded"] = not probs
        if present and not probs:
            rec["status"] = "loaded"
        if probs and present:
            self.say("The check after reloading failed: " + "; ".join(probs[:5]))
            self.auto_undo(doc, rec)
            return I.EXIT_REFUSED
        if probs:
            rec["status"] = "reverted-on-disk"
            self.say("Reverted on disk, but Hyprland still shows: " + "; ".join(probs[:5]))
            return I.EXIT_REFUSED
        if not present:
            rec["status"] = "reverted"
        self.say(("Applied and loaded: %s. The layer rules (blur, no compositor animation) reach the shell's main "
                  "layer the next time it is created: restart the shell once (log out and back in, or restart its "
                  "service)." % registered(rec.get("skipped") or ()))
                 if present else
                 "Reverted and reloaded: none of the %d shortcuts is registered any more." % shortcut_count())
        return I.EXIT_OK

    def auto_undo(self, doc, rec):
        """A6: deshacer sólo si el principal sigue siendo EXACTAMENTE lo escrito; si no, conflicto y manual."""
        try:
            cur = open(rec["main"], "rb").read()
        except OSError:
            cur = b""
        if sha(cur) != rec["shaAfter"]:
            rec["status"] = "conflict"
            rec["conflict"] = {"current": rec["main"], "displaced": None}
            self.say("%s changed after it was written: it is left as it is. Remove the sumi-shell lines by hand, then "
                     "`install.sh hyprland --revert`." % rec["main"])
            return I.EXIT_REFUSED
        return self.revert_steps(doc, rec, "")

    # -- revert --
    def hyprland_revert(self, doc, t, rec):
        doc = self.need_install()
        rec = (doc.get("integrations") or {}).get("hyprland")
        if not rec or rec.get("status") == "reverted":
            self.say("Nothing to revert for Hyprland.")
            return I.EXIT_OK
        if t.get("autoreload", True) and not self.args.reload:
            raise I.Refused(["with automatic reload on, changing %s makes Hyprland reload its whole configuration. Pass "
                             "--reload to allow it" % rec["main"]])
        errors_before = hyprctl("configerrors")[1].strip()
        return self.run_tx(doc, "hyprland-revert", rec, lambda tx: self.revert_steps(doc, rec, errors_before))

    def revert_steps(self, doc, rec, errors_before):
        res = {"r": "absent"}
        try:
            st, cur = os.lstat(rec["main"]), open(rec["main"], "rb").read()
        except OSError:
            st, cur = None, None
        if cur is not None:
            block = rec["block"].encode()
            full = (b"\n" if rec.get("addedNewline") else b"") + block
            new = cur.replace(full, b"", 1) if cur.count(full) == 1 else cur.replace(block, b"", 1)
            rec["pendingFrom"], rec["pendingNew"] = sha(cur), sha(new)

        def main():
            if cur is None:
                res["r"] = "gone"
                return
            n = cur.count(block)
            if n == 0:
                marker = (">>> sumi-shell (install %s)" % rec["block"].split("(install ", 1)[1].split(")", 1)[0]).encode()
                res["r"] = "edited" if marker in cur else "absent"
                return
            if n > 1:
                res["r"] = "many"
                return
            r, info = replace_file(rec["main"], self.roots, st.st_ino, sha(cur), new, doc["transaction"]["id"],
                                   os.path.basename(rec["main"]) + ".integrated", doc["createdDirs"])
            res["r"], res["info"] = r, info
            if r == "done":
                rec["kept"].append({"rel": info, "sha": sha(cur), "why": "%s with the integration, before reverting" %
                                    rec["main"], "redundant": True})
                rec["restored"] = sha(new) == rec["shaBefore"]
                for k in rec["kept"]:
                    if k["sha"] == rec["shaBefore"] and rec["restored"]:
                        k["redundant"] = True
            elif r == "conflict":
                rec["status"] = "conflict"
                rec["conflict"] = info
        self.step(doc, "main", main)
        if res["r"] == "many":
            raise I.Refused(["%s has the sumi-shell lines more than once: remove them by hand" % rec["main"]])
        if res["r"] == "edited":
            raise I.Refused(["the sumi-shell lines in %s were edited: they are left as they are (and so is %s). "
                             "Remove those lines by hand, then run `install.sh %s --revert` again" % (
                                 rec["main"], rec["fragment"], rec["kind"])])
        if res["r"] == "conflict":
            self.say_conflict(rec)
            return I.EXIT_REFUSED
        if res["r"] == "changed":
            raise I.Refused(["%s changed while it was being written: nothing was changed, run it again" % rec["main"]])
        if res["r"] in ("absent", "gone"):
            self.say("The sumi-shell lines are no longer in %s (removed by you or another tool): it is left as it is."
                     % rec["main"])
        fr = {}
        self.step(doc, "fragment", lambda: fr.update(r=remove_fragment(rec["fragment"], self.roots, rec["fragmentSha"])))
        if fr.get("r") in ("kept", "aside"):
            self.say("%s was changed after it was written: it is kept, and no longer managed." % rec["fragment"])
            rec["fragmentKept"] = True
        rec["status"] = "reverted"
        self.prune_kept(rec)
        if rec["kind"] == "hyprland":
            return self.reload_and_verify(doc, rec, False, errors_before)
        return self.hypridle_after_write(doc, rec, False)

    def prune_kept(self, rec):
        """Tras revertir: las copias que el archivo actual ya contiene se retiran DICIÉNDOLO; las demás se quedan."""
        keep = []
        for k in rec.get("kept", []):
            path = os.path.join(self.roots.real["state"], k["rel"])
            if k.get("redundant"):
                parts = k["rel"].split("/")
                try:
                    dfd = self.roots.chain("state", tuple(parts[:-1]))
                except (FileNotFoundError, I.Refused):
                    continue
                try:
                    r = I.remove_if(dfd, parts[-1], k["sha"])
                finally:
                    os.close(dfd)
                if r in ("removed", "absent"):
                    self.say("  removed the kept copy %s (%s): the current file already has that content" % (path, k["why"]))
                    continue
            keep.append(k)
            self.say("  kept copy: %s (%s)" % (path, k["why"]))
        rec["kept"] = keep

    def say_conflict(self, rec):
        c = rec.get("conflict") or {}
        self.say("%s changed while install.sh was writing it, and again after: NOTHING was restored. Both versions are "
                 "kept:" % rec["main"])
        self.say("  current file:      %s" % c.get("current"))
        if c.get("displaced"):
            self.say("  the other version: %s" % c.get("displaced"))
        self.say("Compare them, keep the one you want as %s (delete the other yourself), then run `install.sh %s "
                 "--revert` (it only removes lines it can recognise) and `install.sh recover --apply`." % (
                     os.path.basename(rec["main"]), rec["kind"]))

    # -- hypridle --
    def hypridle(self):
        doc = self.man.load()
        tree = os.path.join(self.roots.real["config"], *I.TREE_REL)
        t = hypridle_target(self.roots, tree)
        rec = ((doc or {}).get("integrations") or {}).get("hypridle")
        if self.args.revert:
            return self.hypridle_revert(doc, t, rec)
        plan = self.hypridle_plan(doc, t, tree) if not t["manual"] else None
        if not self.args.apply:
            return self.hypridle_preview(t, rec, plan)
        return self.hypridle_apply(doc, t, rec, plan, tree)

    def hypridle_plan(self, doc, t, tree):
        """Qué claves pondría el fragmento, qué exige una opción, y la garantía antes de suspender (MP-1, MP-7, A7, A20)."""
        lc = I.load_module("sumi_lockchain", os.path.join("packaging", "lockchain.py"))
        ctx = {"tree": os.path.realpath(tree), "knownWrappers": I.KNOWN_WRAPPERS}
        g = dict(t["general"])
        helper = os.path.join(tree, "scripts", "sumi-lock")
        keys, need, notes = {}, [], []
        lock = g.get("lock_cmd", "")
        lv = lc.classify_command(lock, ctx)[0] if lock else "none"
        if lv in ("depends", "wrapper"):
            return {"already": True}
        if not lock:
            keys["lock_cmd"] = helper
        elif self.args.replace_lock_cmd:
            keys["lock_cmd"] = helper
        else:
            need.append("lock_cmd is `%s` (it locks your session): replacing it needs --replace-lock-cmd" % lock)
        before = g.get("before_sleep_cmd", "")
        if not before:
            keys["before_sleep_cmd"] = helper + " instant"
        elif REQUESTER.match(before):
            notes.append("before_sleep_cmd asks logind to lock (`%s`): kept; it ends in the new lock_cmd" % before)
        elif lc.classify_command(before, ctx)[0] in ("depends", "wrapper"):
            notes.append("before_sleep_cmd already uses the shell")
        elif self.args.replace_before_sleep_cmd:
            keys["before_sleep_cmd"] = helper + " instant"
        else:
            need.append("before_sleep_cmd is `%s` (it locks before suspending): replacing it needs "
                        "--replace-before-sleep-cmd" % before)
        after = dict(g, **keys)
        if self.args.inhibit_sleep:
            keys["inhibit_sleep"] = "3"
            after["inhibit_sleep"] = "3"
        was, will = waits_for_lock(g), waits_for_lock(after)
        if was and not will:
            need.append("today suspend waits until the session is locked (inhibit_sleep %s with %s); with the new "
                        "lock_cmd it wouldn't. Pass --inhibit-sleep 3 to keep that guarantee (measured: only 3 waits "
                        "for a lock that isn't hyprlock)" % (g.get("inhibit_sleep") or "unset", "hyprlock" if "hyprlock" in
                                                             lock else lock))
        elif not will:
            notes.append("suspend won't wait until the session is locked (inhibit_sleep %s): --inhibit-sleep 3 makes it "
                         "wait (your value is kept unless you pass it)" % (after.get("inhibit_sleep") or "unset"))
        return {"already": False, "keys": keys, "need": need, "notes": notes, "before": {k: g.get(k, "") for k in keys},
                "waitsBefore": was, "waitsAfter": will, "helper": helper}

    def render_idle(self, plan, mid):
        lines = ["# Sumi Shell for hypridle. Written by `install.sh hypridle --apply` (install %s)." % mid,
                 "# Remove it with `install.sh hypridle --revert`. Your idle timeouts and other settings stay yours.",
                 "general {"]
        for k in ("lock_cmd", "before_sleep_cmd", "inhibit_sleep"):
            if k in plan["keys"]:
                lines.append("    %s = %s" % (k, plan["keys"][k]))
        lines.append("}")
        return ("\n".join(lines) + "\n").encode()

