# ---- política de archivos del usuario (A4, A17) ---------------------------------------------------------------------

def file_policy(path, roots, key="config"):
    """Motivos (lista) por los que `path` no se puede editar con seguridad; vacío = se puede."""
    why = []
    base = roots.real[key]
    real_parent = os.path.realpath(os.path.dirname(path))
    if os.path.commonpath([os.path.abspath(path), base]) != base:
        return ["%s is outside %s" % (path, base)]
    rel = os.path.relpath(os.path.dirname(path), base)
    parts = [] if rel == "." else rel.split("/")
    why += roots.parts_problems(key, parts)
    if real_parent != os.path.join(base, *parts):
        why.append("a directory on the way to %s is a symbolic link (dotfiles managers like Stow do this)" % path)
    try:
        st = os.lstat(path)
    except FileNotFoundError:
        return why + ["%s doesn't exist" % path]
    if stat.S_ISLNK(st.st_mode):
        why.append("%s is a symbolic link (dotfiles managers like Stow do this): the installer won't edit what it "
                   "points to" % path)
        return why
    if not stat.S_ISREG(st.st_mode):
        why.append("%s is not a regular file" % path)
    if st.st_uid != os.geteuid():
        why.append("%s is not yours" % path)
    if st.st_nlink != 1:
        why.append("%s has other hard links: replacing it would split them" % path)
    try:
        if os.listxattr(path, follow_symlinks=False):
            why.append("%s has extended attributes or an ACL that replacing it would lose" % path)
    except OSError:
        pass
    try:
        open(path, "rb").read().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        why.append("%s is not readable UTF-8 text" % path)
    sd = os.path.join(roots.real["state"])
    try:
        if os.stat(os.path.dirname(path)).st_dev != os.stat(sd).st_dev:
            why.append("%s and the installer's state (%s) are on different filesystems: the displaced version can't be "
                       "kept atomically" % (path, sd))
    except OSError:
        why.append("the installer's state directory (%s) doesn't exist" % sd)
    return why


# ---- escribir el principal: RENAME_EXCHANGE, todas las versiones conservadas (§5.1) -----------------------------------

EXCHANGE = 2


def exchange(dfd, a, b):
    r = I._libc.renameat2(dfd, a.encode(), dfd, b.encode(), EXCHANGE)
    if r != 0:
        e = I.ctypes.get_errno()
        raise OSError(e, os.strerror(e))


def open_parent(path, roots, key="config"):
    rel = os.path.relpath(os.path.dirname(path), roots.real[key])
    parts = () if rel == "." else tuple(rel.split("/"))
    return roots.chain(key, parts)


def read_regular(dfd, name):
    fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=dfd)
    try:
        st = os.fstat(fd)
        data = b""
        while True:
            b = os.read(fd, 1 << 16)
            if not b:
                break
            data += b
        return st, data
    finally:
        os.close(fd)


def backups_dir(roots, tx, created):
    """$XDG_STATE_HOME/sumi-shell/install/backups/<tx> (0700)."""
    fd = roots.chain("state", I.INSTALL_REL + ("backups",), create=True, created=created)
    try:
        os.mkdir(tx, 0o700, dir_fd=fd)
    except FileExistsError:
        pass
    nfd = I.open_dir(fd, tx)
    os.close(fd)
    os.fchmod(nfd, 0o700)
    return nfd


def replace_file(path, roots, want_ino, want_sha, new, tx, kept_name, created):
    """Sustituye `path` por `new` si sigue siendo (want_ino, want_sha). Resultado:
       ("done", backup)        hecho; la versión anterior se movió a las copias (`backup`, relativa al estado)
       ("changed", None)       el archivo cambió antes de empezar o durante: nada cambió (deshecho el intercambio)
       ("conflict", info)      cambió durante Y después del intercambio: todo se queda donde está (info = rutas)"""
    dfd = open_parent(path, roots)
    name = os.path.basename(path)
    cand = ".%s.sumi-%s" % (name, tx)
    try:
        try:
            st, data = read_regular(dfd, name)
        except FileNotFoundError:
            return "changed", None
        if (st.st_ino, sha(data)) != (want_ino, want_sha):
            return "changed", None
        I.write_new(dfd, cand, new, stat.S_IMODE(st.st_mode))
        c_ino = os.stat(cand, dir_fd=dfd, follow_symlinks=False).st_ino
        I.race(name, "exchange")
        exchange(dfd, cand, name)
        I.race(name, "exchanged")
        try:
            ost, odata = read_regular(dfd, cand)
        except FileNotFoundError:
            ost, odata = None, b""
        if ost is not None and (ost.st_ino, sha(odata)) == (want_ino, want_sha):
            bfd = backups_dir(roots, tx, created)
            try:
                I.rename_noreplace(dfd, cand, bfd, kept_name)
            finally:
                os.close(bfd)
            os.fsync(dfd)
            return "done", "/".join(I.INSTALL_REL + ("backups", tx, kept_name))
        # el archivo cambió entre leerlo e intercambiarlo: ¿el principal sigue siendo EXACTAMENTE lo que escribimos?
        try:
            mst, mdata = read_regular(dfd, name)
        except FileNotFoundError:
            mst, mdata = None, b""
        if mst is not None and mst.st_ino == c_ino and sha(mdata) == sha(new):
            exchange(dfd, cand, name)                       # su versión vuelve a su sitio; la nuestra, al candidato
            cst, cdata = read_regular(dfd, cand)
            if cst.st_ino == c_ino and sha(cdata) == sha(new):
                os.unlink(cand, dir_fd=dfd)                 # sólo la nuestra, comprobada
            return "changed", None
        return "conflict", {"current": path, "displaced": os.path.join(os.path.dirname(path), cand)}
    finally:
        os.close(dfd)


def create_fragment(path, roots, data, created):
    dfd = open_parent(path, roots)
    try:
        I.write_new(dfd, os.path.basename(path), data, 0o644)
        os.fsync(dfd)
    finally:
        os.close(dfd)


def remove_fragment(path, roots, want):
    try:
        dfd = open_parent(path, roots)
    except FileNotFoundError:
        return "absent"
    try:
        return I.remove_if(dfd, os.path.basename(path), want)
    finally:
        os.close(dfd)


