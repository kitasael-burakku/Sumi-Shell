def sha(b):
    return hashlib.sha256(b).hexdigest()


def run_cmd(argv, timeout=15, env=None, cwd=None):
    try:
        p = subprocess.run(argv, capture_output=True, text=True, timeout=timeout, env=env, cwd=cwd)
        return p.returncode, p.stdout, p.stderr
    except (OSError, subprocess.TimeoutExpired) as e:
        return 127, "", str(e)


def hyprctl(*args, timeout=10):
    exe = shutil.which("hyprctl")
    if not exe:
        return 127, "", "hyprctl not found"
    return run_cmd([exe] + list(args), timeout=timeout)


def hj(*args):
    rc, out, err = hyprctl("-j", *args)
    try:
        return json.loads(out)
    except ValueError:
        return None


def vtuple(text):
    m = re.search(r"(\d+)\.(\d+)(?:\.(\d+))?", text or "")
    return tuple(int(x or 0) for x in m.groups()) if m else None


def vstr(t):
    return ".".join(str(x) for x in t)


def hyprland_versions(running):
    """{'running': (0, 57, 0) | None, 'installed': … | None}: lo que dicen el Hyprland en marcha y el binario instalado
    (tras actualizar sin reiniciar pueden diferir: el siguiente inicio de sesión usa el instalado)."""
    out = {"running": None, "installed": None}
    if running:
        v = hj("version")
        if isinstance(v, dict):
            out["running"] = vtuple(str(v.get("version") or v.get("tag") or ""))
    exe = shutil.which("Hyprland")
    if exe:
        rc, o, e = run_cmd([exe, "--version-json"], timeout=10)
        try:
            out["installed"] = vtuple(str(json.loads(o).get("version") or ""))
        except (ValueError, AttributeError):
            pass
    return out


