def real_version():
    """La versión del Hyprland instalado de verdad (`--version-json`), o None."""
    hypr = shutil.which("Hyprland")
    if not hypr:
        return None
    try:
        p = T.subprocess.run([hypr, "--version-json"], capture_output=True, text=True, timeout=20)
        return json.loads(p.stdout).get("version") or None
    except (OSError, ValueError, T.subprocess.TimeoutExpired):
        return None


def probe_hyprlang():
    """¿Lee hyprlang el Hyprland instalado? (detectado: --verify-config de un hyprland.conf mínimo en una carpeta temporal)."""
    hypr = shutil.which("Hyprland")
    if not hypr:
        return False, "Hyprland isn't installed"
    d = T.tempfile.mkdtemp(prefix="kt6e-probe-")
    try:
        f = os.path.join(d, "probe.conf")
        open(f, "w").write("general {\n    gaps_in = 3\n}\n")
        env = {"PATH": "/usr/bin:/bin", "HOME": d, "XDG_CONFIG_HOME": d, "XDG_RUNTIME_DIR": d}
        p = T.subprocess.run([hypr, "--verify-config", "--config", f], capture_output=True, text=True, timeout=60, env=env,
                             cwd=d)
        if p.returncode == 0 and "config ok" in p.stdout:
            return True, ""
        lines = [re.sub(r"\x1b\[[0-9;]*m", "", l).strip() for l in (p.stdout + p.stderr).splitlines()]
        last = [l for l in lines if (f + ":") in l][:1] or [l for l in lines if l][-1:] or ["no output"]
        return False, ("the installed Hyprland %s doesn't read hyprland.conf (hyprlang): `Hyprland --verify-config` of a "
                       "minimal hyprlang file says «%s»" % (REAL_VERSION or "?", last[0].replace(f, "probe.conf")))
    finally:
        shutil.rmtree(d, ignore_errors=True)


