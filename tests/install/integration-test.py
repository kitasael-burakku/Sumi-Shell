class Bench(T.Bench):
    def __init__(self, spec=None, dialect="lua", main=None, installed=True, hyprland=True, version="real", binary="real"):
        """version: la que dice `hyprctl -j version` ("real" = la del Hyprland instalado; None = no contesta). binary: si
        no es "real", `Hyprland` es el FALSO y dice esa versión (None: no la sabe)."""
        spec = dict({"hyprlock": True}, **(spec or {}))
        super().__init__(spec)
        for n in REAL_TOOLS:
            real = shutil.which(n)
            if real and not os.path.exists(os.path.join(self.shim, n)):
                os.symlink(real, os.path.join(self.shim, n))
        if binary != "real":
            self.fake_hyprland(binary)
        self.dialect = dialect
        self.main = os.path.join(self.cfg, "hypr", "hyprland.lua" if dialect == "lua" else "hyprland.conf")
        self.write(os.path.relpath(self.main, self.h), main if main is not None else (LUA_MAIN if dialect == "lua"
                                                                                       else CONF_MAIN))
        version = REAL_VERSION if version == "real" else version
        if version:
            self.spec.update(hyprVersion=version, hyprLuaDispatcher=lua_dispatcher(version))
        if hyprland:
            self.spec.update(hyprProc=True, hyprDialect=dialect, hyprMain=self.main,
                             hyprInstances=[{"instance": SIG, "time": int(time.time()) - 600, "pid": 6161,
                                             "wl_socket": "wayland-1"}],
                             hyprUserBinds=[{"modmask": 64, "key": "RETURN", "dispatcher": "__lua" if dialect == "lua"
                                             else "exec", "arg": "kitty", "description": ""}])
            self.spec["hyprBinds"] = list(self.spec["hyprUserBinds"])
            log = os.path.join(self.run_dir, "hypr", SIG, "hyprland.log")
            os.makedirs(os.path.dirname(log), exist_ok=True)
            # la línea que dice qué archivo cargó: la de 0.56, o la de 0.57 si el banco dice serlo (medido el 2026-10-30)
            if lua_dispatcher(version) != "__lua":
                line = "DEBUG ]: [Config::initConfigManager] [cfg] Regular config at %s\n" % self.main
            else:
                line = "DEBUG ]: [cfg] %s %s\n" % ("Using lua config found at" if dialect == "lua" else
                                                   "Lua config not found, using legacy config at", self.main)
            open(log, "w").write(line)
        self.save_spec()
        if installed:
            rc, out = self.run("install", "--enable")
            assert rc == 0, out

    def fake_hyprland(self, version):
        """`Hyprland` y `readelf` falsos: readelf contesta por el Hyprland real (la Lua que enlaza, M3)."""
        real, readelf = shutil.which("Hyprland"), shutil.which("readelf")
        for n in ("Hyprland", "readelf"):
            if os.path.lexists(os.path.join(self.shim, n)):
                os.unlink(os.path.join(self.shim, n))
        f = os.path.join(self.shim, "Hyprland")
        open(f, "w").write(FAKE_HYPRLAND.replace("@PYTHON@", os.path.realpath(sys.executable)).replace("@FIX@", self.fix)
                           .replace("@REAL@", real or "/nonexistent"))
        os.chmod(f, 0o755)
        if readelf:
            r = os.path.join(self.shim, "readelf")
            open(r, "w").write('#!/bin/sh\nfor a; do shift; [ "$a" = "%s" ] && a="%s"; set -- "$@" "$a"; done\nexec %s "$@"\n'
                               % (f, real or "/nonexistent", readelf))
            os.chmod(r, 0o755)
        self.spec["hyprBinVersion"] = version

    def set_versions(self, running=None, binary=None):
        self.spec = self.load_spec()
        if running:
            self.spec.update(hyprVersion=running, hyprLuaDispatcher=lua_dispatcher(running))
        if binary:
            self.spec["hyprBinVersion"] = binary
        self.save_spec()

    def man(self):
        return json.load(open(os.path.join(self.h, T.MANIFEST)))

    def integ(self, kind):
        return (self.man().get("integrations") or {}).get(kind)

    def frag(self):
        return os.path.join(os.path.dirname(self.main), "sumi-shell.lua" if self.dialect == "lua" else
                            "sumi-shell.conf")

    def body(self, p):
        return open(p, "rb").read()

    def ours(self):
        return [b for b in self.load_spec().get("hyprBinds", []) if str(b.get("description", "")).startswith("Sumi Shell:")]

    def load_spec(self):
        return json.load(open(os.path.join(self.fix, "spec.json")))

    def cfgsnap(self):
        return {k: v for k, v in self.snap().items() if k.startswith(".config/")}


def both(fn):
    def run(b, probs):
        for d in ("lua", "conf"):
            if d == "conf" and not HYPRLANG:
                skip("[conf]")
                continue
            c = Bench(dialect=d)
            try:
                sub = []
                fn(c, sub)
                probs += ["[%s] %s" % (d, p) for p in sub]
            finally:
                c.close()
    return run


