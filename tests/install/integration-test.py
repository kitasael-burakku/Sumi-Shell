def apply_revert_cycle(b, probs):
    orig = b.body(b.main)
    cfg_before = b.cfgsnap()
    rc, out = b.run("hyprland", "--apply", "--reload")
    expect(rc == 0 and "%d shortcuts are registered" % NSC in out, "apply: %d %s" % (rc, out[-400:]), probs)
    # vidrio (2026-11-07): las reglas de capa del fragmento = las del ejemplo Lua (api-check las cruza con el árbol), y el
    # aviso de que la capa principal ya abierta sólo las recibe al reiniciar la shell
    expect("restart the shell once" in out, "no restart notice for the layer rules: %s" % out[-300:], probs)
    if b.dialect == "lua":
        rules = lambda text: re.findall(r"^hl\.layer_rule\(.*\)$", text, re.M)
        example = open(os.path.join(T.ROOT, "sumi", "examples", "hyprland", "sumi.lua"), encoding="utf-8").read()
        got = rules(b.body(b.frag()).decode()) if os.path.exists(b.frag()) else []
        expect(len(got) == 3 and got == rules(example), "fragment layer rules ≠ the example: %s" % got, probs)
    rec = b.integ("hyprland")
    expect(rec and rec["status"] == "loaded", "status %s" % (rec or {}).get("status"), probs)
    expect(len(b.ours()) == NSC, "%d bindings of ours" % len(b.ours()), probs)
    expect(b.body(b.main).startswith(orig) and b"sumi-shell (install" in b.body(b.main), "main not appended", probs)
    kept = rec["kept"][0]
    kp = os.path.join(b.state, kept["rel"])
    expect(os.path.exists(kp) and hashlib.sha256(open(kp, 'rb').read()).hexdigest() == kept["sha"], "the version before isn't kept", probs)
    expect(oct(os.stat(os.path.dirname(kp)).st_mode & 0o777) == "0o700", "backups dir not private", probs)
    rc, out = b.run("hyprland", "--apply", "--reload")
    expect(rc == 0 and "Already applied" in out, "second apply: %d %s" % (rc, out[-200:]), probs)
    rc, out = b.run("hyprland", "--revert", "--reload")
    expect(rc == 0 and "none of the %d" % NSC in out, "revert: %d %s" % (rc, out[-400:]), probs)
    expect(b.body(b.main) == orig, "main isn't byte for byte the original", probs)
    expect(not os.path.exists(b.frag()), "fragment left", probs)
    expect(b.cfgsnap() == cfg_before, "~/.config differs: %s" % T.diff_snap(cfg_before, b.cfgsnap())[:5], probs)
    expect("removed the kept copy" in out and not os.path.exists(kp), "kept copies not pruned (or silently): %s" % out[-300:],
           probs)
    expect(b.integ("hyprland")["status"] == "reverted", "status after revert", probs)


s_apply_revert = both(apply_revert_cycle)


