def s_idle_interrupted(b, probs):
    for op in ("apply", "revert"):
        for step in ("fragment", "main"):
            for when in ("before", "after"):
                c = idle_bench("listener {\n    timeout = 300\n    on-timeout = loginctl lock-session\n}\n")
                tag = "%s %s:%s" % (op, step, when)
                try:
                    orig = open(idle_main(c), "rb").read()
                    if op == "revert":
                        c.run("hypridle", "--apply")
                    rc, out = c.run("hypridle", "--" + op, extra={"SUMI_INSTALL_FAULT": "%s:%s:SIGKILL" % (step, when)})
                    expect(rc == -9, "%s: rc %d" % (tag, rc), probs)
                    m = open(idle_main(c)).read()
                    if "sumi-shell (install" in m:
                        expect(os.path.exists(idle_frag(c)), "%s: a source line without its file" % tag, probs)
                    rc, out = c.run("recover", "--apply")
                    expect(rc == 0, "%s: recover %d %s" % (tag, rc, out[-300:]), probs)
                    expect(open(idle_main(c), "rb").read() == orig and not os.path.exists(idle_frag(c)),
                           "%s: not back to the original" % tag, probs)
                finally:
                    c.close()


def s_idle_race(b, probs):
    c = idle_bench("listener {\n    timeout = 300\n    on-timeout = loginctl lock-session\n}\n")
    try:
        user = b"# the user's hypridle.conf, saved meanwhile\n"
        c.main = idle_main(c)

        def act(path):
            open(path + ".tmp", "wb").write(user)
            os.rename(path + ".tmp", path)
        rc, o = race(c, "hypridle", ["--apply"], "hypridle.conf", "exchange", act)
        expect(rc == 1 and open(idle_main(c), "rb").read() == user and not os.path.exists(idle_frag(c)),
               "race on hypridle.conf: %d %s" % (rc, o[-300:]), probs)
    finally:
        c.close()


