def lua_dispatcher(version):
    v = tuple(int(x) for x in (version or "0.0").split(".")[:2])
    return "HL.Dispatcher(global)" if v >= (0, 57) else "__lua"


# El Hyprland falso de los casos con versión fijada (spec: hyprBinVersion). Lua → el real; hyprlang con ≤ 0.56 → «config ok»
# si las llaves cuadran; hyprlang con ≥ 0.57 → lo que dice el real (lo lee como Lua).
FAKE_HYPRLAND = r'''#!@PYTHON@
import json, os, sys
a = sys.argv[1:]
fix = "@FIX@"          # fijo: verify_fragment lo lanza con un entorno mínimo, sin KT_FIX
spec = json.load(open(os.path.join(fix, "spec.json")))
open(os.path.join(fix, "argv.log"), "a").write(json.dumps(["Hyprland"] + a) + "\n")
v = spec.get("hyprBinVersion")
if a == ["--version-json"]:
    print(json.dumps({"version": v, "tag": "v%s" % v}) if v else "garbage"); sys.exit(0 if v else 1)
if a[:1] == ["--verify-config"] and "--config" in a:
    f = a[a.index("--config") + 1]
    if f.endswith(".conf") and v and tuple(int(x) for x in v.split(".")[:2]) < (0, 57):
        t = open(f).read()
        ok = t.count("{") == t.count("}")
        print("\n======== Config parsing result:\n\n" + ("config ok" if ok else "%s:1: unbalanced braces" % f))
        sys.exit(0 if ok else 1)
    os.execv("@REAL@", ["Hyprland"] + a)
sys.exit(1)
'''
