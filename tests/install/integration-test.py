def main():
    args = sys.argv[1:]
    out_json = None
    if args[:1] == ["--json"]:
        out_json, args = args[1], args[2:]
    only = args
    fails = 0
    rows = []
    if not HYPRLANG:
        print("hyprlang: %s → its [conf] parts are SKIPPED (not passed)" % HYPRLANG_WHY)
    for name, fn in SCENARIOS.items():
        if only and name not in only:
            continue
        b = T.Bench()
        probs = []
        del SKIPS[:]
        try:
            fn(b, probs)
        except Exception as e:
            import traceback
            probs.append("harness: %s" % traceback.format_exc()[-600:])
        finally:
            b.close()
        fails += 1 if probs else 0
        skipped = list(SKIPS)
        result = "fail" if probs else ("pass, parts skipped" if skipped else "pass")
        rows.append({"scenario": name, "result": result, "problems": probs, "skipped": skipped})
        print("%-70s %s%s%s" % (name, "PASS" if not probs else "FAIL",
                                ("  (skipped: %s)" % ", ".join(skipped)) if skipped else "",
                                ("  " + "; ".join(probs)) if probs else ""))
    leftovers = [d for d, _, _ in os.walk(T.ROOT) if os.path.basename(d) == "__pycache__"]
    if leftovers:
        fails += 1
        print("__pycache__ left in the repo: %s" % leftovers)
    nskip = sum(1 for r in rows if r["skipped"])
    print("failed: %d · scenarios with skipped parts: %d%s" % (fails, nskip, (" (%s)" % HYPRLANG_WHY) if nskip else ""))
    if out_json:
        json.dump({"hyprland": REAL_VERSION, "hyprlang": HYPRLANG, "skipReason": HYPRLANG_WHY or None,
                   "passed": sum(1 for r in rows if r["result"] == "pass"),
                   "passedWithSkips": sum(1 for r in rows if r["result"] == "pass, parts skipped"),
                   "failed": fails, "scenarios": rows}, open(out_json, "w"), indent=1, ensure_ascii=False)
    return fails


if __name__ == "__main__":
    sys.exit(main())
