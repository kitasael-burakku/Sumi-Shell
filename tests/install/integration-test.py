def race(b, verb, args, name, point, act):
    sync = os.path.join(b.tmp, "race-%s" % point)
    os.mkdir(sync)
    p = b.run(verb, *args, extra={"SUMI_INSTALL_RACE": "%s:%s:%s" % (name, point, sync)}, wait=False)
    end = time.monotonic() + 60
    while not os.path.exists(os.path.join(sync, "ready")):
        if time.monotonic() > end or p.poll() is not None:
            p.kill()
            return -1, "never reached %s: %s" % (point, p.communicate()[0][-300:])
        time.sleep(0.01)
    act(b.main)
    open(os.path.join(sync, "go"), "x").close()
    o, _ = p.communicate(timeout=120)
    return p.returncode, o


def race2(b, name, before, after):
    """Dos paradas: «exchange» (antes) y «exchanged» (después). El enganche sólo para una vez por proceso: dos procesos no;
    aquí se usa un solo proceso y la segunda acción se hace en la primera parada… pero DESPUÉS de soltarla no hay otra. Por
    eso la segunda pausa se pide con un archivo de control propio del banco (SUMI_INSTALL_RACE2)."""
    s1 = os.path.join(b.tmp, "r1")
    s2 = os.path.join(b.tmp, "r2")
    os.mkdir(s1)
    os.mkdir(s2)
    p = b.run("hyprland", "--apply", "--reload", extra={"SUMI_INSTALL_RACE": "%s:exchange:%s" % (name, s1),
                                                        "SUMI_INSTALL_RACE2": "%s:exchanged:%s" % (name, s2)}, wait=False)
    for sync, act in ((s1, before), (s2, after)):
        end = time.monotonic() + 60
        while not os.path.exists(os.path.join(sync, "ready")):
            if time.monotonic() > end or p.poll() is not None:
                p.kill()
                return -1, "never reached: %s" % p.communicate()[0][-300:]
            time.sleep(0.01)
        act(b.main)
        open(os.path.join(sync, "go"), "x").close()
    o, _ = p.communicate(timeout=120)
    return p.returncode, o


def s_interrupted(b, probs):
    steps = {"apply": ("fragment", "main", "reload"), "revert": ("main", "fragment", "reload")}
    for dialect in ("lua", "conf"):
        if dialect == "conf" and not HYPRLANG:
            skip("[conf]")
            continue
        for op, names in steps.items():
            for step in names:
                for when in ("before", "after"):
                    for sig in ("SIGTERM", "SIGKILL"):
                        c = Bench(dialect=dialect)
                        tag = "[%s] %s %s:%s:%s" % (dialect, op, step, when, sig)
                        try:
                            orig = c.body(c.main)
                            cfg0 = c.cfgsnap()
                            if op == "revert":
                                c.run("hyprland", "--apply", "--reload")
                            rc, out = c.run("hyprland", "--" + op, "--reload",
                                            extra={"SUMI_INSTALL_FAULT": "%s:%s:%s" % (step, when, sig)})
                            if rc == 0 and sig == "SIGTERM" and step == "reload":
                                # SIGTERM se atiende entre pasos: tras el último, la orden termina. Estado coherente:
                                if op == "apply":
                                    expect(len(c.ours()) == NSC and c.integ("hyprland")["status"] == "loaded",
                                           "%s: finished but not loaded" % tag, probs)
                                else:
                                    expect(c.body(c.main) == orig and not c.ours(), "%s: finished but not reverted" % tag,
                                           probs)
                                continue
                            if rc not in (3, -9):
                                probs.append("%s: rc %d %s" % (tag, rc, out[-200:]))
                                continue
                            rc, out = c.run("recover", "--apply")
                            expect(rc == 1 and "--reload" in out, "%s: recover without --reload must refuse: %d" % (tag, rc),
                                   probs)
                            rc, out = c.run("recover", "--apply", "--reload")
                            expect(rc == 0, "%s: recover rc %d %s" % (tag, rc, out[-300:]), probs)
                            expect(c.body(c.main) == orig, "%s: main isn't the original after recover" % tag, probs)
                            expect(not os.path.exists(c.frag()), "%s: fragment left" % tag, probs)
                            left = [n for n in os.listdir(os.path.dirname(c.main)) if ".sumi-" in n]
                            expect(not left, "%s: leftovers %s" % (tag, left), probs)
                            expect(c.cfgsnap() == cfg0, "%s: ~/.config differs" % tag, probs)
                            expect(not c.ours(), "%s: still bound after recover" % tag, probs)
                        finally:
                            c.close()


