#!/usr/bin/env python3
"""Sumi Shell — el inventario completo del IPC `sumi`, clasificado (portabilidad F6b, 2026-10-12).

Uso: ipc-inventory.py <árbol sumi/> <contract.json> <salida.md>

Genera api/IPC-INVENTORY.md a partir del código. Sólo DOCUMENTA: lo único estable es lo público (el contrato); este
archivo no se comprueba y puede regenerarse cuando cambie lo interno.
  public       está en el contrato (API.md)
  internal     lo usan los scripts, unidades o ejemplos del propio árbol (lockNow, notifServer…), o es una función de
               la shell sin promesa de compatibilidad (puede cambiar con cualquier versión)
  diagnostic   pruebas y banco: el nombre lo dice (…Test…, …TestRoot, …State, …Probe) o su comentario
               (SÓLO BANCO, SÓLO PRUEBAS, «Pruebas:», «para probar»…)
"""
import json
import os
import re
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import importlib.util  # noqa: E402

spec = importlib.util.spec_from_file_location("api_check", os.path.join(os.path.dirname(__file__), "api-check.py"))
api_check = importlib.util.module_from_spec(spec)
spec.loader.exec_module(api_check)

DIAG_NAME = re.compile(r"Test|State$|Probe|Dump")
DIAG_COMMENT = re.compile(r"S[ÓO]LO (EN EL )?BANCO|S[ÓO]LO PRUEBAS|PRUEBAS\b|^Pruebas|[Pp]ara (las )?pruebas|para PROBAR|"
                          r"de prueba|testRoot|sustituto", re.M)


def comments(tree):
    lines = api_check.read(tree, "core/Ipc.qml").splitlines()
    res = {}
    for i, l in enumerate(lines):
        m = re.match(r"\s*function (\w+)\(", l)
        if not m:
            continue
        j, block = i - 1, []
        while j >= 0 and lines[j].strip().startswith(("*", "/*", "//", "*/")):
            t = lines[j].strip().lstrip("/*").strip()
            if t:
                block.append(t)
            j -= 1
        res[m.group(1)] = " ".join(reversed(block))
    return res


def first_sentence(text):
    t = re.sub(r"\s+", " ", text).strip()
    m = re.match(r"(.{0,140}?[.;:])(\s|$)", t)
    return (m.group(1) if m else t[:140]).replace("|", "\\|")


# Quién depende de cada verbo NO público que se usa fuera de QML, y por qué camino. No es contrato público, pero romperlo
# rompe la shell: un cambio tiene que llevar su llamador en el mismo commit (api-check, control `internal`, lo vigila).
CHAINS = {
    "lockNow": "Lock: `loginctl lock-session` → hypridle `lock_cmd`/`before_sleep_cmd` → `scripts/sumi-lock [session|instant]` "
               "→ `lockNow <reason>`; si no bloquea, el helper lanza hyprlock. También el botón Lock en modo directo (F5d)",
    "lockStatus": "Lock: `scripts/sumi-lock rescue` (unidad `sumi-lock-rescue.service`) lo lee para no lanzar hyprlock si la "
                  "shell volvió y sostiene el bloqueo. Es también público (lectura)",
    "notifServer": "Notifications: `scripts/notif-server shell|off` lo usa para guardar el ajuste del servidor antes de reiniciar la "
                   "shell y escribir o borrar la activación D-Bus",
    "status": "Notifications: `scripts/notif-server` lee `.notifs` (enabled, running…) para saber si el cambio entró. Lo que lee "
              "fuera de los campos garantizados es interno: cambiarlo exige cambiar notif-server",
    "reload": "Units: `ExecReload` de `systemd/sumi-shell.service`. Es también público",
}


def main():
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    tree, contract_path, out = sys.argv[1:]
    c = json.load(open(contract_path))
    public = set(c["ipc"]["verbs"])
    sigs = api_check.ipc_signatures(tree)
    com = comments(tree)
    own = api_check.internal_calls(tree)
    rows, counts = [], {"public": 0, "internal": 0, "diagnostic": 0}
    for v in sorted(sigs, key=str.lower):
        types, ret = sigs[v]
        if v in public:
            cls = "public"
        elif v in own:
            cls = "internal"
        elif DIAG_NAME.search(v) or DIAG_COMMENT.search(com.get(v, "")):
            cls = "diagnostic"
        else:
            cls = "internal"
        counts[cls] += 1
        note = "used by " + ", ".join(sorted(own[v])) if v in own and v not in public else first_sentence(com.get(v, ""))
        rows.append("| `%s` | `(%s) → %s` | %s | %s |" % (v, ", ".join(types), ret, cls, note))
    head = ["# IPC inventory (`qs -c sumi ipc call sumi <verb>`)", "",
            "Generated by `tests/api/ipc-inventory.py` from `sumi/core/Ipc.qml`. **Only the `public` verbs are a "
            "contract** (see [API.md](../API.md)); `internal` and `diagnostic` verbs may change or disappear in any "
            "version. Notes are the first line of each verb's comment in the code (often in Spanish).", "",
            "%d verbs: %d public, %d internal, %d diagnostic." % (len(sigs), counts["public"], counts["internal"],
                                                                 counts["diagnostic"]), "",
            "| Verb | Signature | Class | Note |", "|---|---|---|---|"]
    deps = ["", "## Verbs the shell's own scripts and units depend on", "",
            "Not all of them are public, but their callers ship in the same tree: a change must update the caller in the same "
            "commit (`api-check` fails, check `internal`, if one of them disappears). Descriptions in Spanish, as in the code.",
            "", "| Verb | Class | Used by | Chain |", "|---|---|---|---|"]
    for v in sorted(own, key=str.lower):
        cls = "public" if v in public else "internal"
        deps.append("| `%s` | %s | %s | %s |" % (v, cls, ", ".join("`%s`" % x for x in sorted(own[v])),
                                                CHAINS.get(v, "").replace("|", "\\|")))
    missing = sorted(set(CHAINS) - set(own))
    if missing:
        raise SystemExit("CHAINS names verbs the tree no longer calls: %s" % missing)
    with open(out, "w") as f:
        f.write("\n".join(head + rows + deps) + "\n")
    print(json.dumps(dict(counts, total=len(sigs))))


if __name__ == "__main__":
    main()
